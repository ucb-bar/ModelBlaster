def _c_ident(name: str) -> str:
    return name.replace(".", "_").replace("-", "_")


def _f32(x: float) -> str:
    """Format a float32 value as a C float literal (round-trip safe).

    Always emits a decimal point or exponent before the `f` suffix so the
    compiler reads it as a float (not an integer with an illegal suffix).
    """
    f = float(np.float32(x))
    if np.isnan(f):
        return "(0.0f/0.0f)"
    if np.isinf(f):
        return "(1.0f/0.0f)" if f > 0 else "(-1.0f/0.0f)"
    s = f"{f:.9g}"
    # `g` may print "0", "1", "-2" with no decimal/exponent — append ".0"
    # so the `f` suffix binds to a floating literal.
    if "." not in s and "e" not in s and "E" not in s and "n" not in s:
        s += ".0"
    return s + "f"


def _array_lines(arr: np.ndarray, per_line: int = 8) -> list[str]:
    flat = arr.astype(np.float32).reshape(-1)
    out: list[str] = []
    for i in range(0, len(flat), per_line):
        chunk = flat[i : i + per_line]
        out.append("    " + ", ".join(_f32(v) for v in chunk) + ",")
    return out


def _array_lines_int(arr: np.ndarray, per_line: int = 16) -> list[str]:
    """Format an integer array as lines of comma-separated decimal literals."""
    flat = arr.reshape(-1)
    out: list[str] = []
    for i in range(0, len(flat), per_line):
        chunk = flat[i : i + per_line]
        out.append("    " + ", ".join(str(int(v)) for v in chunk) + ",")
    return out


# Map our IR dtype tags to C scalar types (used everywhere — buffer decls,
# run_model signature, weights.h, test_io.h). _Float16 is the standard
# scalar half-precision type in C — gcc supports it natively when
# compiling with `-march=...zfh` for RISC-V (Dima's Aug-13 patch wires
# this up automatically when CONFIG_RISCV_ISA_EXT_ZFH=y).
_DTYPE_TO_C = {
    "f32": "float",
    "f16": "_Float16",
    "i8":  "int8_t",
    "i32": "int32_t",
    "i64": "int64_t",
}


def _dtype_to_c(dtype: str) -> str:
    if dtype not in _DTYPE_TO_C:
        raise NotImplementedError(f"unknown IR dtype: {dtype}")
    return _DTYPE_TO_C[dtype]


def _np_to_c_dtype(np_dtype) -> tuple[str, str]:
    """(c_type, ir_dtype_tag) for a numpy weight blob's dtype."""
    if np_dtype == np.float32:
        return "float", "f32"
    if np_dtype == np.float16:
        return "_Float16", "f16"
    if np_dtype == np.int8:
        return "int8_t", "i8"
    if np_dtype == np.int32:
        return "int32_t", "i32"
    if np_dtype == np.int64:
        return "int64_t", "i64"
    raise NotImplementedError(f"unsupported weight dtype: {np_dtype}")


def _prod(shape: list[int]) -> int:
    n = 1
    for s in shape:
        n *= int(s)
    return n


def _buf_name(mid: str, tensor: str) -> str:
    """Intermediate-buffer symbol name. Mangled with the model id so
    multiple models can have a `buf_x` and still link without collision
    when the buffers are emitted with external (non-static) linkage.
    External linkage is required by the heterogeneous (harness_xpurt)
    flow: each (model, backend) is its own OBJECT lib, so file-static
    buffers would give each backend its own private copy and cross-
    backend dispatches would read zeroed scratch. The buffers TU is
    compiled once per model (NOT per backend) and shared by all
    backends; same model.c source compiled per backend re-uses the
    single shared definition via `extern` declarations."""
    return f"buf_{mid}_{_c_ident(tensor)}"


