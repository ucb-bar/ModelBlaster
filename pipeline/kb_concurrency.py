def tail(sched: dict, policy: str, nops: int, prefix: str) -> list[str]:
    """The walker's ``launch_gpu_implementation`` (and helpers) for a concurrency-enabled export."""
    if not sched or not sched["concurrent"]:
        return [*_BUDGET_FN.replace("@WIDTH@", "").splitlines(),
                "static int mb_conc_width(int) { return 1; }",
                "void launch_gpu_implementation(void **b) {",
                f"    for (int i = 0; i < {nops}; ++i) mb_run_op(i, b);", "}",
                'extern "C" int mb_so_conc() { return 0; }']
    ofs, flat = [0], []
    for p in sched["preds"]:
        flat += p
        ofs.append(len(flat))
    lane_cases = []
    for k in range(sched["n"]):
        if sched["lane"][k]:
            sid = sched["slots"][k]
            st = sched["stmts"][k].replace(f"{prefix}{sid}::", f"{prefix}{sid}__lane{sched['lane'][k]}::")
            lane_cases.append(f"    case {k}: {st} break;")
    width = sched["width"] if policy != "none" else [1] * sched["n"]

    def arr(name, vals):
        vals = list(vals) or [0]
        return f"static const int {name}[] = {{{', '.join(map(str, vals))}}};"

    out = ["// ---- concurrent branches (kb_concurrency): DAG of the ops, lanes, SM budget",
           f"// policy {policy}; max width {sched['max_width']}; hazard edges {sched['edges_hazard']}",
           f"static const int MB_CONC_N = {sched['n']};",
           arr("MB_PRED_OFS", ofs), arr("MB_PRED", flat), arr("MB_WIDTH", width),
           f"static const int MB_STRICT = {1 if policy == 'strict' else 0};",
           *_BUDGET_FN.replace("@WIDTH@", "").splitlines(),
           "static int mb_conc_width(int i) { return MB_WIDTH[i]; }",
           "// an op on its lane's copy of its slot (lane 0 = the slot itself)",
           "static void mb_run_op_lane(int i, void **b) {", "    switch (i) {", *lane_cases,
           "    default: mb_run_op(i, b); break;", "    }", "}",
           *_CONC_LAUNCH.splitlines(),
           'extern "C" int mb_so_conc() { return 1; }']
    return out


_BUDGET_FN = r"""#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>
#include <thread>
#include <algorithm>
static int g_mb_conc_w = 1;                  // concurrent branches around the op being issued (1: alone)
extern "C" int mb_sm_budget(void) {
    static int sms = 0;
    if (!sms) { int d = 0; cudaGetDevice(&d); cudaDeviceGetAttribute(&sms, cudaDevAttrMultiProcessorCount, d); if (sms <= 0) sms = 1; }
    const char *f = getenv("MB_SM_BUDGET");            // a fixed budget (tests)
    if (f && *f && atoi(f) > 0) return std::min(atoi(f), sms);
    return g_mb_conc_w > 1 ? std::max(1, sms / g_mb_conc_w) : sms;
}"""

_CONC_LAUNCH = r"""// MB_CONCURRENCY=0: sequential (the deadlock fallback); else concurrent while the stream is being captured
static bool mb_conc_on() {
    const char *e = getenv("MB_CONCURRENCY");
    if (e && !strcmp(e, "0")) return false;
    cudaStreamCaptureStatus st = cudaStreamCaptureStatusNone;
    return cudaStreamIsCapturing(cudaStreamPerThread, &st) == cudaSuccess && st == cudaStreamCaptureStatusActive;
}
static bool mb_cap_deps(std::vector<cudaGraphNode_t> &out) {
    cudaStreamCaptureStatus st; const cudaGraphNode_t *d = nullptr; size_t nd = 0;
#if CUDART_VERSION >= 13000
    if (cudaStreamGetCaptureInfo(cudaStreamPerThread, &st, nullptr, nullptr, &d, nullptr, &nd) != cudaSuccess) return false;
#else
    if (cudaStreamGetCaptureInfo(cudaStreamPerThread, &st, nullptr, nullptr, &d, &nd) != cudaSuccess) return false;
#endif
    out.assign(d, d + nd);
    return st == cudaStreamCaptureStatusActive;
}
static void mb_set_deps(std::vector<cudaGraphNode_t> &v) {
    std::sort(v.begin(), v.end()); v.erase(std::unique(v.begin(), v.end()), v.end());
#if CUDART_VERSION >= 13000
    cudaStreamUpdateCaptureDependencies(cudaStreamPerThread, v.empty() ? nullptr : v.data(), nullptr, v.size(),
                                        cudaStreamSetCaptureDependencies);
#else
    cudaStreamUpdateCaptureDependencies(cudaStreamPerThread, v.empty() ? nullptr : v.data(), v.size(),
                                        cudaStreamSetCaptureDependencies);
#endif
}
// strict policy: does op i launch a one-wave grid (it may rely on co-residency) above its budget? Probed once, its
// launches captured alone on a helper thread (its own per-thread stream) with its budget set
static int mb_probe_state[1 << 16];
static bool mb_exclusive(int i, void **b) {
    if (!MB_STRICT || MB_WIDTH[i] <= 1 || i >= (1 << 16)) return false;
    if (mb_probe_state[i]) return mb_probe_state[i] == 2;
    int viol = 0;
    std::thread([&] {
        cudaStream_t s = cudaStreamPerThread;
        cudaGraph_t g = nullptr;
        int w0 = g_mb_conc_w; g_mb_conc_w = MB_WIDTH[i];
        if (cudaStreamBeginCapture(s, cudaStreamCaptureModeThreadLocal) != cudaSuccess) { viol = 1; g_mb_conc_w = w0; return; }
        mb_run_op_lane(i, b);
        cudaError_t e = cudaStreamEndCapture(s, &g);
        g_mb_conc_w = w0;
        if (e != cudaSuccess || !g) { viol = 1; cudaGetLastError(); return; }
        size_t nn = 0; cudaGraphGetNodes(g, nullptr, &nn);
        std::vector<cudaGraphNode_t> nodes(nn); if (nn) cudaGraphGetNodes(g, nodes.data(), &nn);
        int d = 0, sms = 1; cudaGetDevice(&d); cudaDeviceGetAttribute(&sms, cudaDevAttrMultiProcessorCount, d);
        int budget = std::max(1, sms / MB_WIDTH[i]);
        for (auto nd : nodes) {
            cudaGraphNodeType t; cudaGraphNodeGetType(nd, &t);
            if (t != cudaGraphNodeTypeKernel) continue;
            cudaKernelNodeParams kp; if (cudaGraphKernelNodeGetParams(nd, &kp) != cudaSuccess) continue;
            long grid = (long)kp.gridDim.x * kp.gridDim.y * kp.gridDim.z;
            int per = 0;
            cudaOccupancyMaxActiveBlocksPerMultiprocessor(&per, kp.func, kp.blockDim.x * kp.blockDim.y * kp.blockDim.z,
                                                          kp.sharedMemBytes);
            if (per > 0 && grid <= (long)per * sms && grid > (long)per * budget) viol = 1;
        }
        cudaGraphDestroy(g);
        cudaGetLastError();
    }).join();
    mb_probe_state[i] = viol ? 2 : 1;
    if (viol) printf("MB_CONC_EXCLUSIVE op %d: a one-wave grid above its SM budget (strict policy)\n", i);
    return viol != 0;
}
static void mb_conc_launch(void **b) {
    std::vector<cudaGraphNode_t> entry, cur;
    if (!mb_cap_deps(entry)) { for (int i = 0; i < MB_CONC_N; ++i) mb_run_op(i, b); return; }
    std::vector<std::vector<cudaGraphNode_t>> term(MB_CONC_N);
    std::vector<char> has_succ(MB_CONC_N, 0);
    std::vector<cudaGraphNode_t> issued, barrier;             // every terminal so far; the last exclusive op's
    for (int i = 0; i < MB_CONC_N; ++i) {
        bool excl = mb_exclusive(i, b);
        std::vector<cudaGraphNode_t> deps;
        if (excl) deps = issued;
        for (int k = MB_PRED_OFS[i]; k < MB_PRED_OFS[i + 1]; ++k) {
            int p = MB_PRED[k]; has_succ[p] = 1;
            deps.insert(deps.end(), term[p].begin(), term[p].end());
        }
        deps.insert(deps.end(), barrier.begin(), barrier.end());
        if (deps.empty()) deps = entry;                       // a root of the partition
        mb_set_deps(deps);
        g_mb_conc_w = MB_WIDTH[i];
        mb_run_op_lane(i, b);
        g_mb_conc_w = 1;
        if (!mb_cap_deps(cur)) return;                        // capture invalidated: the driver reports it
        term[i] = cur;
        issued.insert(issued.end(), cur.begin(), cur.end());
        if (excl) barrier = cur;
    }
    std::vector<cudaGraphNode_t> fin;
    for (int i = 0; i < MB_CONC_N; ++i) if (!has_succ[i]) fin.insert(fin.end(), term[i].begin(), term[i].end());
    if (fin.empty()) fin = entry;
    mb_set_deps(fin);                                         // the stream joins every branch
}
// lane copies keep their own lazily initialised state (a slot's first call may cudaMalloc its scratch, which a stream
// capture forbids): eager launches run every op on its lane, and before the first capture the lane copies are run
// once, eagerly, on a helper thread (its own per-thread stream; this thread's capture is unaffected)
static bool mb_lanes_warm = false;
static void mb_warm_lanes(void **b) {
    if (mb_lanes_warm) return;
    std::thread([&] {
        for (int i = 0; i < MB_CONC_N; ++i) mb_run_op_lane(i, b);
        cudaStreamSynchronize(cudaStreamPerThread);
    }).join();
    cudaGetLastError();
    mb_lanes_warm = true;
}
void launch_gpu_implementation(void **b) {
    if (!mb_conc_on()) {
        cudaStreamCaptureStatus st = cudaStreamCaptureStatusNone;
        bool cap = cudaStreamIsCapturing(cudaStreamPerThread, &st) == cudaSuccess && st != cudaStreamCaptureStatusNone;
        for (int i = 0; i < MB_CONC_N; ++i) { if (cap) mb_run_op(i, b); else mb_run_op_lane(i, b); }
        if (!cap) mb_lanes_warm = true;
        return;
    }
    mb_warm_lanes(b);
    mb_conc_launch(b);
}"""


# ---------------------------------------------------------------- driver watchdog

WATCHDOG = r"""
// ---- deadlock watchdog (kb_concurrency): concurrent branches of persistent / spin-waiting kernels can hang when
// their blocks are not co-resident. Every graph launch arms a timer; a replay not done after MB_CONC_TIMEOUT_S
// (default 30 s) ends the process (a spinning kernel cannot be stopped in-process). Rerun with MB_CONCURRENCY=0.
static cudaEvent_t mb_wd_ev = nullptr;
static std::atomic<double> mb_wd_t0{0.0};
static void mb_wd_start() {
    static bool started = false;
    if (started) return;
    started = true;
    cudaEventCreateWithFlags(&mb_wd_ev, cudaEventDisableTiming);
    std::thread([] {
        for (;;) {
            std::this_thread::sleep_for(std::chrono::milliseconds(200));
            double t0 = mb_wd_t0.load(), lim = 1000.0 * env_num("MB_CONC_TIMEOUT_S", 30.0);
            if (t0 > 0 && mb_now_ms() - t0 > lim && cudaEventQuery(mb_wd_ev) == cudaErrorNotReady) {
                printf("MB_CONC_DEADLOCK graph replay not finished after %.0f s (concurrent branches); "
                       "rerun with MB_CONCURRENCY=0\nMB_ERROR MB_CONC_DEADLOCK\nfailed\n", lim / 1000.0);
                fflush(stdout);
                _exit(5);
            }
        }
    }).detach();
}
static cudaError_t mb_graph_launch(cudaGraphExec_t g, cudaStream_t s) {
    mb_wd_start();
    cudaError_t e = cudaGraphLaunch(g, s);
    cudaEventRecord(mb_wd_ev, s);
    mb_wd_t0.store(mb_now_ms());
    return e;
}
"""


def driver(src: str) -> str:
    """A driver.cpp with the watchdog (every ``cudaGraphLaunch`` armed) and the concurrency variables per request."""
    src = src.replace("cudaGraphLaunch(", "mb_graph_launch(")
    anchor = "static void *dev[NB];"
    assert anchor in src
    src = src.replace(anchor, anchor + "\n" + _WD_DECL, 1)
    src = src.replace("static int mb_setup() {", WATCHDOG + "\nstatic int mb_setup() {", 1)
    src = src.replace('"MB_ATTR", "MB_OP_US_PASS", "MB_WALL", "MB_WARM", "MB_THRU_N"};',
                      '"MB_ATTR", "MB_OP_US_PASS", "MB_WALL", "MB_WARM", "MB_THRU_N", "MB_CONCURRENCY",\n'
                      '                                  "MB_SM_BUDGET", "MB_CONC_TIMEOUT_S"};', 1)
    src = src.replace("#include <vector>\n", "#include <vector>\n#include <unistd.h>\n", 1)
    return src


_WD_DECL = "static cudaError_t mb_graph_launch(cudaGraphExec_t g, cudaStream_t s);   // the watchdog's (below)"
