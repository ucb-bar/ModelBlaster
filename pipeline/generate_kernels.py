def _generate_one_llm_for_algorithm(
    spec: KernelSpec,
    algorithm,  # AlgorithmCandidate
    shapes: list[dict],
    client: BedrockClient,
    backend: Backend,
    correctness_system: str,
    max_retries: int,
    log,
    *,
    impls: dict[str, str],
    specs: list[KernelSpec],
    repo_root: Optional[str],
    model_dir: Optional[str],
    build_dir: Optional[str],
    harness_dir: Optional[str],
    io_path: Optional[str],
    cache_dir: Optional[str] = None,
) -> Optional[str]:
    """Try to drive Bedrock to produce a kernel implementing `algorithm`
    for this spec. Returns C source on success, None on giving up.
    """
    # Cache hit: if we have a previously-verified kernel for this
    # (op, target, algorithm) triple, reverify it and skip the LLM if it
    # still passes. Cache key is per-algorithm so different algos don't
    # clobber each other.
    cache_path = (
        os.path.join(cache_dir, f"{backend.name}_{spec.op}_{algorithm.name}.c")
        if cache_dir else None
    )
    if cache_path and os.path.exists(cache_path):
        cached = open(cache_path).read()
        log(f"  [{spec.op}/{algorithm.name}] trying cached kernel from {cache_path}")
        vres = _verify(
            spec, cached, shapes, backend=backend,
            impls=impls, specs=specs,
            repo_root=repo_root, model_dir=model_dir,
            build_dir=build_dir, harness_dir=harness_dir, io_path=io_path,
            algorithm_name=algorithm.name,
        )
        if vres.ok:
            log(f"  [{spec.op}/{algorithm.name}] cache HIT — {vres.message}")
            return cached
        log(f"  [{spec.op}/{algorithm.name}] cache stale "
            f"({vres.message.splitlines()[0]}); regenerating")

    prev_code: Optional[str] = None
    prev_diag: Optional[str] = None
    for attempt in range(1, max_retries + 1):
        if prev_code is None:
            user = _correctness_user_prompt(spec, shapes, algorithm)
        else:
            user = _retry_prompt(prev_code, prev_diag or "(no diagnostic)")
        log(f"  [{spec.op}/{algorithm.name}] attempt {attempt}/{max_retries}: "
            f"calling {client.model_id}")
        temp = 0.0 if attempt == 1 else 0.3
        res = client.converse(user=user, system=correctness_system,
                              max_tokens=2048, temperature=temp)
        log(f"  [{spec.op}/{algorithm.name}] tokens "
            f"in={res.input_tokens} out={res.output_tokens} "
            f"stop={res.stop_reason}")
        candidate = extract_code_block(res.text, lang="c")
        vres = _verify(
            spec, candidate, shapes, backend=backend,
            impls=impls, specs=specs,
            repo_root=repo_root, model_dir=model_dir,
            build_dir=build_dir, harness_dir=harness_dir, io_path=io_path,
            algorithm_name=algorithm.name,
        )
        if vres.ok:
            log(f"  [{spec.op}/{algorithm.name}] verify PASS — {vres.message}")
            if cache_path:
                os.makedirs(os.path.dirname(cache_path), exist_ok=True)
                with open(cache_path, "w") as f:
                    f.write(candidate)
                log(f"  [{spec.op}/{algorithm.name}] cached -> {cache_path}")
            return candidate
        # Print the first line of the diagnostic on the verify-FAIL line,
        # then dump the full message at low verbosity. Knowing exactly
        # which compile error / golden mismatch fired is essential when
        # the LLM keeps regenerating the same broken pattern.
        first_line = vres.message.splitlines()[0] if vres.message.strip() \
            else "(no diagnostic returned)"
        log(f"  [{spec.op}/{algorithm.name}] verify FAIL — {first_line}")
        if vres.message.strip() and len(vres.message.splitlines()) > 1:
            for line in vres.message.splitlines()[1:]:
                log(f"      {line}")
        prev_code = candidate
        prev_diag = vres.message
    log(f"  [{spec.op}/{algorithm.name}] gave up after {max_retries} attempts")
    return None


def generate_one_llm(
    spec: KernelSpec,
    shapes: list[dict],
    client: BedrockClient,
    backend: Backend,
    correctness_system: str,
    max_retries: int,
    log,
    *,
    impls: dict[str, str],
    specs: list[KernelSpec],
    repo_root: Optional[str],
    model_dir: Optional[str],
    build_dir: Optional[str],
    harness_dir: Optional[str],
    io_path: Optional[str],
    cache_dir: Optional[str] = None,
    algorithm_filter: Optional[set[str]] = None,
) -> Optional[tuple[str, str]]:
    """Try each algorithm in spec.algorithms in order. First one that
    produces a passing kernel wins. Returns ``(code, algorithm_name)`` so
    callers can track which algorithm was selected (e.g. to write the
    optimized variant back to the right cache file).
    `algorithm_filter` (if set) restricts
    to a subset of algorithm names — but if NO algorithms on this spec
    match the filter (e.g. user asked for 'im2col_gemm' but `linear` only
    has 'direct'), fall back to the spec's full algorithm list rather than
    failing the run. The filter is best-thought-of as "prefer these where
    available", not "only these everywhere".
    """
    if algorithm_filter is None:
        candidates = list(spec.algorithms)
    else:
        candidates = [a for a in spec.algorithms if a.name in algorithm_filter]
        if not candidates:
            log(f"  [{spec.op}] filter {sorted(algorithm_filter)} matches "
                f"none of this op's algorithms "
                f"{[a.name for a in spec.algorithms]}; falling back to all")
            candidates = list(spec.algorithms)
    # Also drop algorithms whose target_affinity excludes this backend.
    candidates = [
        a for a in candidates
        if not a.target_affinity or backend.name in a.target_affinity
    ]
    if not candidates:
        log(f"  [{spec.op}] no algorithms remain after target_affinity "
            f"filter for target {backend.name}")
        return None
    log(f"  [{spec.op}] algorithm queue: "
        f"{[a.name for a in candidates]}")

    # First pass: probe the cache across ALL candidate algorithms and
    # pick the one whose cached kernel is fastest in the spike harness.
    # This avoids picking the lexically-first algorithm when a slower
    # one is cached but a faster alternative also is — e.g. when both
    # `direct` (slow) and `im2col_gemm` (fast) are cached for conv2d on
    # RVV, we want to use im2col_gemm. The probe is a harness build+run
    # per cache HIT, but builds are incremental so this is cheap once
    # warmed up.
    if cache_dir is not None:
        best_cached_code: Optional[str] = None
        best_cached_algo: Optional[str] = None
        best_cached_cycles: Optional[int] = None
        for algorithm in candidates:
            cache_path = os.path.join(
                cache_dir, f"{backend.name}_{spec.op}_{algorithm.name}.c")
            if not os.path.exists(cache_path):
                continue
            cached = open(cache_path).read()
            log(f"  [{spec.op}/{algorithm.name}] probing cached kernel")
            vres = _verify(
                spec, cached, shapes, backend=backend,
                impls=impls, specs=specs,
                repo_root=repo_root, model_dir=model_dir,
                build_dir=build_dir, harness_dir=harness_dir, io_path=io_path,
                algorithm_name=algorithm.name,
            )
            if not vres.ok:
                log(f"  [{spec.op}/{algorithm.name}] cache stale "
                    f"({vres.message.splitlines()[0]})")
                continue
            cyc = (vres.cycles_by_op or {}).get(spec.op)
            log(f"  [{spec.op}/{algorithm.name}] cache HIT — "
                f"{cyc if cyc is not None else '?'} cycles")
            if best_cached_cycles is None or (cyc is not None and cyc < best_cached_cycles):
                best_cached_code = cached
                best_cached_algo = algorithm.name
                best_cached_cycles = cyc
        if best_cached_code is not None:
            log(f"  [{spec.op}] using cached algorithm '{best_cached_algo}' "
                f"({best_cached_cycles} cycles, fastest of cached options)")
            return best_cached_code, best_cached_algo

    # No cache hits — generate for each algorithm in order, take the
    # first one that verifies. (This is the original behavior; it's
    # the correct shape when there's no prior cycle data to compare.)
    for algorithm in candidates:
        code = _generate_one_llm_for_algorithm(
            spec, algorithm, shapes, client, backend, correctness_system,
            max_retries, log,
            impls=impls, specs=specs,
            repo_root=repo_root, model_dir=model_dir,
            build_dir=build_dir, harness_dir=harness_dir, io_path=io_path,
            cache_dir=cache_dir,
        )
        if code is not None:
            log(f"  [{spec.op}] using algorithm '{algorithm.name}'")
            return code, algorithm.name
    log(f"  [{spec.op}] all {len(candidates)} algorithms exhausted")
    return None


def collect_shapes(ir: dict, op: str, spec: KernelSpec) -> list[dict]:
    return shapes_from_ir(ir, op) + spec.extra_shapes


# ---------------------------------------------------------------------------
# Beam-search optimize loop
# ---------------------------------------------------------------------------

def _normalize(code: str) -> str:
    return " ".join(code.split())


def beam_search_optimize(
    spec: KernelSpec,
    shapes: list[dict],
    baseline_code: str,
    baseline_cycles: int,
    *,
    impls: dict[str, str],
    specs: list[KernelSpec],
    backend: Backend,
    client: BedrockClient,
    optimize_system: str,
    repo_root: str,
    model_dir: str,
    build_dir: str,
    harness_dir: str,
    io_path: Optional[str],
    beam: int,
    expansions: int,
    iterations: int,
    log,
) -> tuple[str, int, list[dict], list[tuple[str, int]]]:
    """Returns (best_code, best_cycles, history, all_viable_proposals).

    `all_viable_proposals` is every distinct (code, spike_cycles) pair
    that survived build+verify across all iterations, sorted by
    cycles ascending. Used downstream by the firesim re-rank step
    to pick the top-K spike survivors and re-score them on real RTL.
    Note: the baseline is NOT in this list — callers should add it.
    """
    from agents.pipeline.profile_kernel import build_and_run, ProfileError

    Beam = list[tuple[str, int]]
    beam_set: Beam = [(baseline_code, baseline_cycles)]
    best_code, best_cycles = baseline_code, baseline_cycles
    seen: set[str] = {_normalize(baseline_code)}
    history: list[dict] = []
    # Cumulative list of every distinct candidate that built+verified
    # successfully (across all iterations). The firesim re-rank step
    # consumes the top-K of this list to score on real RTL.
    all_viable: list[tuple[str, int]] = []

    for it in range(1, iterations + 1):
        log(f"  [{spec.op}] iter {it}/{iterations}  beam=[{', '.join(str(c) for _, c in beam_set)}]  best={best_cycles}")
        proposals: Beam = []
        for parent_idx, (parent_code, parent_cycles) in enumerate(beam_set):
            for exp in range(1, expansions + 1):
                log(f"    parent {parent_idx} ({parent_cycles} cyc) exp {exp}/{expansions}: calling LLM")
                user = _optimize_user_prompt(
                    spec, shapes, parent_code, parent_cycles,
                    parent_history=[(c, cy) for c, cy in beam_set if c != parent_code],
                )
                res = client.converse(
                    user=user, system=optimize_system,
                    max_tokens=2048, temperature=0.5,
                )
                log(f"      tokens in={res.input_tokens} out={res.output_tokens}")
                candidate = extract_code_block(res.text, lang="c")
                key = _normalize(candidate)
                if key in seen:
                    log(f"      duplicate, skip")
                    continue
                seen.add(key)

                # Combined verify + profile in one harness build.
                trial = dict(impls)
                trial[spec.op] = candidate
                try:
                    hres = build_and_run(
                        trial, specs, backend=backend,
                        model_dir=model_dir, build_dir=build_dir,
                        repo_root=repo_root, harness_dir=harness_dir,
                        pristine=False, io_path=io_path,
                    )
                except ProfileError as e:
                    # Surface the actual gcc error / spike trace so the loop
                    # operator can spot patterns. Keep the first 3 non-empty
                    # lines — usually enough to see the diagnostic without
                    # drowning the log.
                    err_lines = [ln for ln in str(e).splitlines() if ln.strip()]
                    head = err_lines[:3]
                    log(f"      build/spike FAIL:")
                    for ln in head:
                        log(f"        {ln[:200]}")
                    history.append({
                        "iter": it, "parent_cycles": parent_cycles,
                        "result": "build_fail",
                        "diag": " | ".join(head)[:600],
                    })
                    continue

                if io_path and hres.golden_ok is False:
                    log(f"      verify FAIL: golden mismatch "
                        f"(max_abs_err={hres.golden_max_abs_err:.3g})")
                    history.append({
                        "iter": it, "parent_cycles": parent_cycles,
                        "result": "verify_fail",
                        "diag": f"golden mismatch ({hres.golden_max_abs_err:.3g})",
                    })
                    continue

                # On host-verifiable backends, also re-run host verify with the
                # numerical sweep — catches cases where the model shapes are
                # narrow but extra_shapes are not.
                if backend.verify_method == VERIFY_HOST_CTYPES:
                    vres = host_verify(spec, candidate, shapes)
                    if not vres.ok:
                        log(f"      host verify FAIL: {vres.message.splitlines()[0]}")
                        history.append({
                            "iter": it, "parent_cycles": parent_cycles,
                            "result": "verify_fail",
                            "diag": vres.message.splitlines()[0],
                        })
                        continue

                new_cycles = hres.cycles_by_op.get(spec.op, 0)
                log(f"      {parent_cycles} -> {new_cycles} cyc"
                    f" ({(parent_cycles-new_cycles)/parent_cycles*100:+.1f}%)")
                history.append({
                    "iter": it, "parent_cycles": parent_cycles,
                    "result": "ok", "cycles": new_cycles,
                })
                proposals.append((candidate, new_cycles))
                all_viable.append((candidate, new_cycles))
                if new_cycles < best_cycles:
                    best_code, best_cycles = candidate, new_cycles

        if not proposals:
            log(f"  [{spec.op}] no surviving proposals this iter, stopping")
            break

        beam_set = sorted(proposals, key=lambda x: x[1])[:beam]
        if beam_set[0][1] >= best_cycles and best_cycles < baseline_cycles:
            log(f"  [{spec.op}] no further improvement, stopping early")
            break

    log(f"  [{spec.op}] BEST: {baseline_cycles} -> {best_cycles} "
        f"({(baseline_cycles - best_cycles) / baseline_cycles * 100:+.1f}%)")
    # Sort viable proposals cheapest-spike first; dedupe identical
    # bodies that may have come up across iterations.
    viable_sorted: list[tuple[str, int]] = []
    seen_norm: set[str] = set()
    for code, cyc in sorted(all_viable, key=lambda x: x[1]):
        key = _normalize(code)
        if key in seen_norm:
            continue
        seen_norm.add(key)
        viable_sorted.append((code, cyc))
    return best_code, best_cycles, history, viable_sorted


