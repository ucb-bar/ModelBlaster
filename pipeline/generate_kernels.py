"""Emit kernels.h + kernels.c for a model IR.

Two orthogonal axes:

  --backend reference|llm           where do kernel implementations come from
  --target  scalar|rvv|...          which HW backend they target

Backends are declared in agents/pipeline/backends.py. Each carries its own
optimization guide (used in correctness AND optimize prompts), prj.conf
overlay, kernel-only compile flags, spike --isa args, and verify routing
(host_ctypes for natively-runnable code, spike_harness for code that needs
to be cross-compiled and exercised on spike).

Optimize phase (--optimize) runs a beam search over LLM-proposed faster
equivalents, gated by per-op cycle measurement on spike with the right
backend args. Tunable via --beam, --expansions, --iterations.
"""

