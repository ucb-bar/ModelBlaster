def _check_signature(candidate: str, spec: KernelSpec) -> Optional[str]:
    """Cheap lexical check that the candidate's first function definition
    matches the expected signature byte-for-byte (whitespace-insensitive,
    parameter names included). Catches LLM mistakes like reordering ints
    before we burn a Zephyr build / spike run on it.
    """
    cand_norm = " ".join(candidate.split())
    sig_norm = " ".join(spec.signature.split())
    if (
        cand_norm.startswith(sig_norm + " {")
        or cand_norm.startswith(sig_norm + "{")
    ):
        return None
    return (
        f"signature mismatch (parameter names/order must match the declaration "
        f"in kernels.h byte-for-byte).\n"
        f"  expected: {sig_norm}\n"
        f"  got:      {cand_norm[: len(sig_norm) + 16]}..."
    )


# Lexical structural checks per algorithm. Kept lightweight: a substring
# search for an identifier we expect to see if Llama actually followed the
# algorithmic structure. False negatives (different naming) drop into the
# slow verify path which still works; the goal is just to fail FAST when
# Llama is obviously not following the algorithm.
_ALGORITHM_REQUIRED_SUBSTRINGS: dict[str, tuple[str, ...]] = {
    # im2col_gemm: must allocate and populate the im2col buffer.
    "im2col_gemm": ("im2col_buf",),
    # oc_blocked: must have an outer OC tile loop. Looking for the
    # `oc_outer` identifier from the seed example is enough to catch the
    # most common LLM mistake (collapsing the outer-OC loop and writing
    # the direct algorithm under the cache-blocked label).
    "oc_blocked": ("oc_outer", "TILE_OC"),
}


def _check_algorithm_structure(candidate: str, algorithm_name: Optional[str]
                               ) -> Optional[str]:
    if algorithm_name is None:
        return None
    required = _ALGORITHM_REQUIRED_SUBSTRINGS.get(algorithm_name)
    if not required:
        return None
    cand_norm = candidate
    missing = [s for s in required if s not in cand_norm]
    if missing:
        return (
            f"algorithm '{algorithm_name}' structural check failed — "
            f"candidate is missing required identifier(s) {missing}. "
            f"This usually means the kernel fused the stages or "
            f"substituted a different algorithm. Re-read the algorithm "
            f"description and produce code that uses the named "
            f"intermediate buffer."
        )
    return None


def _verify(
    spec: KernelSpec, candidate: str, shapes: list[dict],
    *, backend: Backend,
    impls: Optional[dict[str, str]] = None,
    specs: Optional[list[KernelSpec]] = None,
    repo_root: Optional[str] = None,
    model_dir: Optional[str] = None,
    build_dir: Optional[str] = None,
    harness_dir: Optional[str] = None,
    io_path: Optional[str] = None,
    algorithm_name: Optional[str] = None,
) -> VerifyResult:
    sig_err = _check_signature(candidate, spec)
    if sig_err is not None:
        return VerifyResult(False, sig_err)
    struct_err = _check_algorithm_structure(candidate, algorithm_name)
    if struct_err is not None:
        return VerifyResult(False, struct_err)

    if backend.verify_method == VERIFY_HOST_CTYPES:
        return host_verify(spec, candidate, shapes)

    if backend.verify_method == VERIFY_SPIKE_HARNESS:
        # Build the full harness with this candidate substituted, run on
        # spike, and require the model output to match the PyTorch golden
        # within tolerance. This is necessarily coarser than per-shape
        # ctypes verify, but it's the only correctness check available for
        # backends with target-only intrinsics.
        if not all([impls is not None, specs is not None, repo_root,
                    model_dir, build_dir, harness_dir, io_path]):
            return VerifyResult(
                False,
                "spike-harness verify requires impls/specs/paths/io to be wired in",
            )
        from agents.pipeline.profile_kernel import build_and_run, ProfileError
        trial = dict(impls)  # type: ignore[arg-type]
        trial[spec.op] = candidate
        try:
            res = build_and_run(
                trial, specs,  # type: ignore[arg-type]
                backend=backend, model_dir=model_dir,  # type: ignore[arg-type]
                build_dir=build_dir,  # type: ignore[arg-type]
                repo_root=repo_root,  # type: ignore[arg-type]
                harness_dir=harness_dir,  # type: ignore[arg-type]
                pristine=False, io_path=io_path,
            )
        except ProfileError as e:
            return VerifyResult(False, f"spike-harness build/run failed:\n{e}")
        if res.golden_ok is False:
            # Decode where the divergence happened so the LLM has something
            # actionable to fix on retry.
            import numpy as _np
            golden = _np.load(io_path)["output"].astype(_np.float32).reshape(-1)  # type: ignore[arg-type]
            actual = res.output.astype(_np.float32) if res.output is not None else None
            extra = ""
            if actual is not None and actual.shape == golden.shape:
                abs_err = _np.abs(actual - golden)
                first = int(_np.argmax(abs_err > 0.0))
                ws = max(0, first - 2)
                we = min(len(golden), first + 6)
                extra = (
                    f"\n  first divergence at output flat_idx={first}\n"
                    f"  output[{ws}:{we}] expected: "
                    f"{[round(float(v), 6) for v in golden[ws:we]]}\n"
                    f"  output[{ws}:{we}] got:      "
                    f"{[round(float(v), 6) for v in actual[ws:we]]}"
                )
            return VerifyResult(
                False,
                f"model output diverged from golden (max_abs_err="
                f"{res.golden_max_abs_err:.3g}, max_rel_err="
                f"{res.golden_max_rel_err:.3g}){extra}",
                max_abs_err=res.golden_max_abs_err,
                max_rel_err=res.golden_max_rel_err,
            )
        return VerifyResult(
            True,
            f"spike-harness ok (max_abs_err={res.golden_max_abs_err:.3g} "
            f"max_rel_err={res.golden_max_rel_err:.3g}, "
            f"cycles={res.cycles_by_op})",
            max_abs_err=res.golden_max_abs_err,
            max_rel_err=res.golden_max_rel_err,
            cycles_by_op=dict(res.cycles_by_op) if res.cycles_by_op else None,
        )

    return VerifyResult(False, f"unknown verify_method {backend.verify_method}")


