def generate(
    ir_path: str,
    out_dir: str,
    backend_name: str,
    target_name: str,
    *,
    max_retries: int = 4,
    optimize: bool = False,
    beam: int = 2,
    expansions: int = 3,
    iterations: int = 2,
    repo_root: Optional[str] = None,
    build_dir: Optional[str] = None,
    harness_dir: str = "agents/harness",
    io_path: Optional[str] = None,
    cache_dir: Optional[str] = None,
    algorithm_filter: Optional[set[str]] = None,
    quant: str = "fp32",
    # Opt-in: after the spike beam search picks a best, re-rank the
    # top-K spike survivors on FireSim RTL. The cache slot is replaced
    # with the firesim-best only if the firesim cycles drop by >=
    # FiresimEvalConfig.replacement_threshold_pct vs. the baseline. Off
    # by default — it's expensive (1-3 min per candidate FPGA build+run).
    firesim_eval: bool = False,
    firesim_top_k: int = 3,
    # Opt-in: include the memory-hierarchy stanza in the optimize-phase
    # system prompt. Only useful when firesim_eval=True (otherwise the
    # spike scorer is blind to cache wins, so the LLM has no incentive
    # to produce them).
    cache_aware_prompt: bool = False,
    firesim_op_filter: Optional[set[str]] = None,
) -> None:
    os.makedirs(out_dir, exist_ok=True)
    with open(ir_path) as f:
        ir = json.load(f)

    # The IR records the quantization mode it was extracted under; reject
    # mismatches (e.g. running an int8 IR through the fp32 codegen) loudly.
    ir_quant = ir.get("quant", "fp32")
    if quant != ir_quant:
        raise SystemExit(
            f"quant mismatch: caller passed --quant={quant} but IR was "
            f"extracted with quant={ir_quant}. Re-extract the model with "
            f"the same quant flag, or pass --quant={ir_quant}."
        )
    if quant not in ("fp32", "int8"):
        raise SystemExit(
            f"quant={quant!r} not implemented in generate_kernels yet "
            f"(have: fp32, int8)."
        )

    target = backends_mod.get(target_name)

    # `view` ops (flatten / dropout in eval mode) compile to a buffer alias in
    # the skeleton and have no kernel — skip them here.
    op_kinds = sorted({op["op"] for op in ir["ops"] if op["op"] != "view"})
    for k in op_kinds:
        if k not in KERNEL_SPECS:
            raise SystemExit(f"unknown op kind in IR: {k}")
    specs = [KERNEL_SPECS[k] for k in op_kinds]

    log = lambda msg: print(msg, flush=True)
    impls: dict[str, str] = {}
    # Per-op tracking of which algorithm was selected during baseline gen.
    # Used by the optimize loop to write the optimized kernel back to the
    # right cache file (same key the baseline read from).
    chosen_algo: dict[str, str] = {}

    needs_harness_paths = (
        target.verify_method == VERIFY_SPIKE_HARNESS
        or optimize
    )
    if needs_harness_paths:
        if not (repo_root and build_dir and io_path):
            raise SystemExit(
                f"target={target.name} verify_method={target.verify_method}"
                f" or --optimize requires --repo-root, --build-dir, --io"
            )

    # Correctness phase.
    if backend_name == "reference":
        log(f"backend=reference  target={target.name}  ops={op_kinds}")
        for spec in specs:
            impls[spec.op] = spec.reference_impl
    elif backend_name == "llm":
        client = BedrockClient()
        guide = _load_backend_guide(target)
        correctness_system = _correctness_system_prompt(target, guide)
        log(f"backend=llm  target={target.name}  ops={op_kinds}  "
            f"model={client.model_id}")
        # Seed impls with reference so spike-harness verify has stand-ins
        # for ops not yet generated.
        for spec in specs:
            impls[spec.op] = spec.reference_impl
        # First pass: write reference + emit so the harness can build at all.
        emit_kernels_h(specs, out_dir, model_name=ir["name"])
        emit_kernels_c(impls, "seed", out_dir, backend=target, model_name=ir["name"])
        for spec in specs:
            shapes = collect_shapes(ir, spec.op, spec)
            log(f"  [{spec.op}] verify shapes={shapes}")
            result = generate_one_llm(
                spec, shapes, client, target, correctness_system,
                max_retries, log,
                impls=impls, specs=specs,
                repo_root=repo_root, model_dir=out_dir,
                build_dir=build_dir, harness_dir=harness_dir, io_path=io_path,
                cache_dir=cache_dir,
                algorithm_filter=algorithm_filter,
            )
            if result is None:
                raise SystemExit(
                    f"failed to generate kernel for op '{spec.op}' "
                    f"after {max_retries} attempts"
                )
            code, chosen = result
            impls[spec.op] = code
            chosen_algo[spec.op] = chosen
    else:
        raise SystemExit(f"unknown --backend: {backend_name}")

    emit_kernels_h(specs, out_dir, model_name=ir["name"])
    emit_kernels_c(impls, backend_name, out_dir, backend=target, model_name=ir["name"])
    print(f"wrote {os.path.join(out_dir, 'kernels.h')}")
    print(f"wrote {os.path.join(out_dir, 'kernels.c')}  "
          f"(source={backend_name} target={target.name})")

    if not optimize:
        return

    # Optimize phase.
    if backend_name != "llm":
        log("optimize: requires --backend llm; reference impls are not expanded.")
        return

    log("")
    log(f"optimize: beam={beam} expansions={expansions} iterations={iterations}")
    log(f"optimize: harness={harness_dir} build_dir={build_dir} target={target.name}")

    from agents.pipeline.profile_kernel import build_and_run, ProfileError

    log("optimize: baseline build + profile (pristine)")
    try:
        baseline = build_and_run(
            impls, specs, backend=target,
            model_dir=out_dir, build_dir=build_dir, repo_root=repo_root,  # type: ignore[arg-type]
            harness_dir=harness_dir, pristine=True, io_path=io_path,
        )
    except ProfileError as e:
        raise SystemExit(f"baseline profile failed:\n{e}")
    if io_path and baseline.golden_ok is False:
        raise SystemExit(
            f"baseline diverged from PyTorch golden "
            f"(max_abs_err={baseline.golden_max_abs_err:.3g}); refusing to optimize"
        )
    baseline_cycles_by_op = baseline.cycles_by_op
    log("optimize: baseline cycles per op kind: "
        + ", ".join(f"{k}={v}" for k, v in sorted(baseline_cycles_by_op.items())))

    guide = _load_backend_guide(target)
    optimize_system = _optimize_system_prompt(target, guide)
    # When firesim_eval is requested with cache_aware_prompt, splice the
    # memory-model stanza into the optimize prompt so the LLM has an
    # explicit incentive to produce cache-locality wins. Only does any
    # good when firesim is also scoring — without it spike still ranks.
    if cache_aware_prompt:
        from agents.optimize.firesim_eval import memory_model_stanza
        stanza = memory_model_stanza()
        optimize_system = optimize_system + "\n\n" + stanza
        log("optimize: prompt enriched with target memory-hierarchy stanza")
    client = BedrockClient()

    # Pre-instantiate the firesim evaluator (one per generate() call). It
    # reuses a separate chipyard build dir from the spike build_dir so
    # the spike beam can rebuild while a firesim run is in flight.
    firesim_evaluator = None
    if firesim_eval:
        from agents.optimize.firesim_eval import (
            FiresimEvaluator, FiresimEvalConfig,
        )
        firesim_build_dir = (build_dir or "") + "_firesim_eval"
        firesim_evaluator = FiresimEvaluator(
            backend=target, impls=impls, specs=specs,
            repo_root=repo_root, model_dir=out_dir,  # type: ignore[arg-type]
            firesim_build_dir=firesim_build_dir,
            harness_dir=harness_dir, io_path=io_path,  # type: ignore[arg-type]
            config=FiresimEvalConfig(),
            log=log,
        )
        log(f"optimize: firesim re-rank ENABLED "
            f"(top_k={firesim_top_k}, build_dir={firesim_build_dir})")

    optimize_summary: dict[str, dict] = {}
    for spec in specs:
        baseline_op = baseline_cycles_by_op.get(spec.op, 0)
        if baseline_op <= 0:
            log(f"  [{spec.op}] no baseline cycles, skipping")
            continue
        log(f"\noptimize [{spec.op}] baseline={baseline_op}")
        shapes = collect_shapes(ir, spec.op, spec)
        best_code, best_cycles, history, viable = beam_search_optimize(
            spec, shapes, impls[spec.op], baseline_op,
            impls=impls, specs=specs, backend=target, client=client,
            optimize_system=optimize_system,
            repo_root=repo_root,  # type: ignore[arg-type]
            model_dir=out_dir,
            build_dir=build_dir,  # type: ignore[arg-type]
            harness_dir=harness_dir, io_path=io_path,
            beam=beam, expansions=expansions, iterations=iterations,
            log=log,
        )

        # FireSim re-rank: take the spike top-K survivors + spike-best
        # baseline and re-score on real RTL. Whichever has the lowest
        # firesim cycles wins for cache promotion. The spike-best stays
        # in `impls` as the in-process working copy (we don't want to
        # let firesim regress correctness silently).
        firesim_history: list[dict] = []
        firesim_best_cycles: Optional[int] = None
        if firesim_evaluator is not None and viable:
            run_op = (
                firesim_op_filter is None
                or spec.op in firesim_op_filter
            )
            if not run_op:
                log(f"  [{spec.op}/firesim] skipped (not in op filter)")
            else:
                # Refresh the evaluator's impls so non-targeted ops use
                # the spike-best from this iteration (otherwise stale
                # reference impls ride along and skew the harness).
                trial_impls = dict(impls)
                trial_impls[spec.op] = best_code
                firesim_evaluator.impls = trial_impls
                from agents.optimize.firesim_eval import evaluate_top_k
                fbest_code, fbest_cycles, firesim_history = evaluate_top_k(
                    spec, viable,
                    evaluator=firesim_evaluator,
                    spike_baseline=(best_code, best_cycles),
                    log=log, k=firesim_top_k,
                )
                if fbest_code is not None and fbest_cycles is not None:
                    firesim_best_cycles = fbest_cycles
                    # Promote to in-process impls + cache only if the
                    # firesim winner differs from the spike baseline.
                    # Identity check is on the normalized code body.
                    if _normalize(fbest_code) != _normalize(best_code):
                        log(f"  [{spec.op}/firesim] promoting firesim-best "
                            f"({fbest_cycles} cyc) over spike-best")
                        best_code = fbest_code

        impls[spec.op] = best_code
        optimize_summary[spec.op] = {
            "baseline": baseline_op,
            "best": best_cycles,
            "improvement_pct": (baseline_op - best_cycles) / baseline_op * 100.0,
            "history": history,
            "firesim_history": firesim_history,
            "firesim_best_cycles": firesim_best_cycles,
        }
        # Persist the optimized kernel back to the same cache slot the
        # baseline read from so a subsequent OPTIMIZE=0 sweep finds the
        # already-improved code on cache HIT and reuses it. Only overwrite
        # when we actually found an improvement — preserves the
        # "baseline LLM" cached file otherwise.
        if cache_dir and best_cycles < baseline_op and spec.op in chosen_algo:
            os.makedirs(cache_dir, exist_ok=True)
            cache_path = os.path.join(
                cache_dir,
                f"{target.name}_{spec.op}_{chosen_algo[spec.op]}.c",
            )
            with open(cache_path, "w") as f:
                f.write(best_code)
            log(f"  [{spec.op}] cached optimized -> {cache_path}")

    emit_kernels_h(specs, out_dir, model_name=ir["name"])
    emit_kernels_c(impls, f"{backend_name}-optimized", out_dir, backend=target, model_name=ir["name"])
    print(f"\nwrote {os.path.join(out_dir, 'kernels.c')}  "
          f"(source={backend_name}-optimized target={target.name})")

    summary_path = os.path.join(out_dir, "optimize_summary.json")
    with open(summary_path, "w") as f:
        json.dump(optimize_summary, f, indent=2)
    log(f"wrote {summary_path}")
    log("")
    log("optimize summary:")
    for op, s in sorted(optimize_summary.items()):
        log(f"  {op}: {s['baseline']} -> {s['best']} ({s['improvement_pct']:+.1f}%)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", required=True, help="graph.json")
    ap.add_argument("--out-dir", required=True,
                    help="output dir for kernels.{c,h} and skeleton C")
    ap.add_argument("--backend", choices=["reference", "llm"], default="reference",
                    help="source of kernel implementations")
    ap.add_argument("--target", default="scalar",
                    help=f"HW backend ({sorted(backends_mod.BACKENDS)})")
    ap.add_argument("--max-retries", type=int, default=4)
    ap.add_argument("--optimize", action="store_true")
    ap.add_argument("--beam", type=int, default=2)
    ap.add_argument("--expansions", type=int, default=3)
    ap.add_argument("--iterations", type=int, default=2)
    ap.add_argument("--repo-root", default=None)
    ap.add_argument("--build-dir", default=None)
    ap.add_argument("--harness-dir", default="agents/harness")
    ap.add_argument("--io", default=None,
                    help="io.npz with the PyTorch golden output (required for "
                         "spike-harness verify and --optimize)")
    ap.add_argument("--cache-dir", default=None,
                    help="reuse PASSing kernels from this dir across runs "
                         "(saves <target>_<op>_<algo>.c on success, "
                         "reverifies on hit)")
    ap.add_argument("--algorithms", default="all",
                    help=("comma-separated algorithm names to try (in order) "
                          "for each op, or 'all' (default) to try every "
                          "algorithm registered on each spec, or 'default' "
                          "to use only the first algorithm of each spec "
                          "(matches old single-seed behavior)"))
    ap.add_argument("--quant", default="fp32",
                    help="quantization mode (fp32 only for now). Must match "
                         "the IR's recorded quant or generate_kernels errors "
                         "out.")
    ap.add_argument("--firesim-eval", action="store_true",
                    help="opt-in: after the spike beam search, re-rank the "
                         "top-K spike survivors on FireSim RTL and promote "
                         "the firesim-best to cache. Expensive (1-3 min "
                         "FPGA build+run per candidate) but the only way "
                         "to capture cache-locality wins. Requires --io.")
    ap.add_argument("--firesim-top-k", type=int, default=3,
                    help="how many spike-best candidates to re-score on "
                         "firesim per op. Total firesim runs per op = K + 1 "
                         "(K survivors + the spike-baseline). Default 3.")
    ap.add_argument("--cache-aware-prompt", action="store_true",
                    help="splice the target's memory-hierarchy stanza into "
                         "the optimize-phase system prompt. Steers the LLM "
                         "toward cache-locality wins. Only useful with "
                         "--firesim-eval (otherwise the scorer is blind).")
    ap.add_argument("--firesim-ops", default=None,
                    help="comma-separated op kinds to firesim re-rank. "
                         "Useful when iterating on just conv2d / linear "
                         "without paying FPGA time on every elementwise op. "
                         "Default (unset) = all ops.")
    args = ap.parse_args()

    if args.algorithms == "all":
        algorithm_filter = None
    elif args.algorithms == "default":
        # Use only the first algorithm of each spec — restored single-seed
        # behavior for back-compat / debugging.
        first_names = {spec.algorithms[0].name for spec in KERNEL_SPECS.values()}
        algorithm_filter = first_names
    else:
        algorithm_filter = {n.strip() for n in args.algorithms.split(",") if n.strip()}

    firesim_op_filter = None
    if args.firesim_ops:
        firesim_op_filter = {
            n.strip() for n in args.firesim_ops.split(",") if n.strip()
        }

    generate(
        args.ir, args.out_dir, args.backend, args.target,
        max_retries=args.max_retries,
        optimize=args.optimize,
        beam=args.beam, expansions=args.expansions, iterations=args.iterations,
        repo_root=args.repo_root, build_dir=args.build_dir,
        harness_dir=args.harness_dir, io_path=args.io,
        cache_dir=args.cache_dir,
        algorithm_filter=algorithm_filter,
        quant=args.quant,
        firesim_eval=args.firesim_eval,
        firesim_top_k=args.firesim_top_k,
        cache_aware_prompt=args.cache_aware_prompt,
        firesim_op_filter=firesim_op_filter,
    )


if __name__ == "__main__":
    main()
