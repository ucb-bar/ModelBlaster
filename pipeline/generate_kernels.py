def _correctness_user_prompt(spec: KernelSpec, shapes: list[dict],
                             algorithm) -> str:
    """Correctness prompt using a specific algorithm seed.

    `algorithm` is an AlgorithmCandidate from spec.algorithms — its
    description and reference_impl tell the LLM what *style* of
    implementation to produce. The verify oracle stays
    spec.reference_impl (algorithm-agnostic) so any equivalent kernel
    passes.
    """
    shapes_lines = "\n".join(f"  - {s}" for s in shapes)
    return f"""\
Implement this kernel:

    {spec.signature};

Semantics:
{spec.semantics}

You are implementing this op using the **{algorithm.name}** algorithm.

Algorithm description:
{algorithm.description}

Here is a correct implementation in this algorithmic style:

```c
{algorithm.reference_impl.rstrip()}
```

CRITICAL — preserve the algorithmic structure. Your job is NOT to substitute
a different, equivalent algorithm. If the reference allocates an
intermediate buffer and fills it before computing the output, your kernel
MUST also allocate and fill that buffer first (then compute). If the
reference has multiple sequential stages (e.g. gather, then matmul), your
kernel MUST keep them as separate stages — don't fuse them into a single
loop nest, even if that would produce equivalent output. The optimization
phase will allow restructuring; this correctness phase only allows
**within-stage** transforms (vectorizing a loop, swapping intrinsics, etc.).
Producing a different algorithm here, even if numerically correct, defeats
the purpose of the algorithm-database design.

Shapes your kernel will be tested at (it must be correct for all of these):
{shapes_lines}

This is the CORRECTNESS phase. Aim for the simplest, most obviously-correct
implementation in the {algorithm.name} algorithmic style that compiles and
matches the verify oracle numerically. There is a separate, later
optimization phase where you'll be asked to produce a faster equivalent.
Loop unrolling, multi-accumulator patterns, tiling, and similar transforms
belong in that later phase — they introduce tail-loop and indexing edge
cases that are easy to get wrong on the first pass. Get correct first.

Remember: ONE ```c block, only the function definition, no extras.
"""


def _retry_prompt(prev_code: str, diagnostic: str) -> str:
    return f"""\
Your previous attempt failed verification. The diagnostic was:

{diagnostic}

Your previous code:

```c
{prev_code}
```

Produce a corrected implementation. Same output rules: one ```c block, only
the function definition, no headers or extras.
"""


def _optimize_user_prompt(
    spec: KernelSpec, shapes: list[dict], baseline_code: str,
    baseline_cycles: int, parent_history: list[tuple[str, int]],
) -> str:
    shapes_lines = "\n".join(f"  - {s}" for s in shapes)
    history_block = ""
    if parent_history:
        history_block = "Earlier attempts you have already made (do not repeat them):\n\n"
        for i, (code, cyc) in enumerate(parent_history, 1):
            history_block += f"Attempt {i} ({cyc} cycles):\n```c\n{code.rstrip()}\n```\n\n"
    return f"""\
Optimize this kernel:

    {spec.signature};

Semantics:
{spec.semantics}

It must remain numerically equivalent to the reference at these test shapes:
{shapes_lines}

Current implementation ({baseline_cycles} cycles total across the model):

```c
{baseline_code.rstrip()}
```

{history_block}\
Produce a faster equivalent. Output the function definition only, in one
```c block.
"""


