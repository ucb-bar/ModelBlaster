#!/usr/bin/env python3
"""Write the curated lstm_q_s8 kernels from pipeline/lstm_q.py (tables + shared integer post stage).

  python scripts/make_lstm_q_kernels.py [--check]

Every lstm_q_s8 kernel embeds the same 513-entry tables and the same post stage (lstm_q.C_POST); only the two
matvecs differ. Generating the files keeps them identical to the reference_impl by construction; --check exits
non-zero if a file on disk differs from what would be generated.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "pipeline"))
import lstm_q  # noqa: E402

HDR = """/* source: curated */
/* algorithm: {algo} */
/* accuracy_class: bit_exact */
/* GENERATED by scripts/make_lstm_q_kernels.py from pipeline/lstm_q.py -- do not edit.
 * lstm_q_s8: integer LSTM cell (pipeline/lower_lstm_int.py). {what}
 * The post stage only sees the exact int32 accumulators, so this kernel equals the reference_impl for any
 * summation order. */
#include <stdint.h>
#include <string.h>
"""

GEMMINI = r"""#include <gemmini.h>
#include <gemmini_params.h>

#ifndef MB_LSTM_Q_MAX_HIDDEN
#define MB_LSTM_Q_MAX_HIDDEN 1024
#endif

/* One accumulator row per gate row: A_x and A_h for all 4H rows of this layer. */
static int32_t mb_lstm_q_ax[4 * MB_LSTM_Q_MAX_HIDDEN] __attribute__((aligned(64)));
static int32_t mb_lstm_q_ah[4 * MB_LSTM_Q_MAX_HIDDEN] __attribute__((aligned(64)));
static int8_t mb_lstm_q_hn[MB_LSTM_Q_MAX_HIDDEN];

/* acc[1, N] = v[1, K] @ W[N, K]^T on Gemmini, raw int32 out (full_C) -- the call linear_s8's
 * gemmini_tiled_matmul makes (bit-exact there, measured). */
static void mb_lstm_q_matvec(const int8_t *v, const int8_t *W, int32_t *acc, int K, int N) {
    tiled_matmul_auto((size_t)1, (size_t)N, (size_t)K, v, W, NULL, (void *)acc,
                      (size_t)K, (size_t)K, (size_t)N, (size_t)N,
                      MVIN_SCALE_IDENTITY, MVIN_SCALE_IDENTITY, (scale_acc_t)1,
                      NO_ACTIVATION, ACC_SCALE_IDENTITY, (acc_scale_t)0,
                      false, false, true, true, false, 0, WS);
}

/* Plain loops: a Gemmini backend's translation unit may be built with a vector -march for a core that
 * has none, so the vectorizer stays off. */
__attribute__((optimize("no-tree-vectorize")))
void kernel_lstm_q_s8(const int8_t *input, const int8_t *w_ih, const int8_t *w_hh,
                      const int32_t *b_ih, const int32_t *b_hh,
                      int8_t *h_state, int8_t *c_state, int8_t *output,
                      int input_size, int hidden_size, int Mx, int Mh, int S,
                      int has_bias) {
    const int H = hidden_size, N = 4 * hidden_size;
    if (H > MB_LSTM_Q_MAX_HIDDEN) return;
    asm volatile("csrs mstatus, %0" : : "r"(0x18000) : "memory");   /* XS = Dirty for RoCC */
    gemmini_flush(0);
    asm volatile("fence" ::: "memory");
    mb_lstm_q_matvec(input, w_ih, mb_lstm_q_ax, input_size, N);
    mb_lstm_q_matvec(h_state, w_hh, mb_lstm_q_ah, H, N);
    gemmini_fence();
    gemmini_flush(0);
    if (has_bias)
        for (int j = 0; j < N; j++) mb_lstm_q_ax[j] += b_ih[j] + b_hh[j];
    for (int t = 0; t < H; t++)
        mb_lstm_q_cell(mb_lstm_q_ax[t], mb_lstm_q_ax[H + t], mb_lstm_q_ax[2 * H + t], mb_lstm_q_ax[3 * H + t],
                       mb_lstm_q_ah[t], mb_lstm_q_ah[H + t], mb_lstm_q_ah[2 * H + t], mb_lstm_q_ah[3 * H + t],
                       Mx, Mh, S, c_state, mb_lstm_q_hn, t);
    for (int t = 0; t < H; t++) { h_state[t] = mb_lstm_q_hn[t]; output[t] = mb_lstm_q_hn[t]; }
}
"""

RVV = r"""#include <riscv_vector.h>

#ifndef MB_LSTM_Q_MAX_HIDDEN
#define MB_LSTM_Q_MAX_HIDDEN 1024
#endif
static int8_t mb_lstm_q_hn[MB_LSTM_Q_MAX_HIDDEN];

/* The four gate rows of unit t (rows t, H+t, 2H+t, 3H+t) against one vector, in one pass: each strip of v
 * is loaded once for four weight strips, so the vector costs 1/4 of the weights' memory traffic (on cores whose
 * vector loads bypass the L1 this matters). int8 x int8 -> int16 (vwmul), accumulated in int32 lanes (vwadd.wv), one
 * reduction per row at the end. */
static inline void mb_lstm_q_dot4(const int8_t *v, const int8_t *W, int K, int H, int t, int32_t out[4]) {
    const size_t vlmax = __riscv_vsetvlmax_e8m1();
    vint32m4_t a0 = __riscv_vmv_v_x_i32m4(0, vlmax), a1 = a0, a2 = a0, a3 = a0;
    const int8_t *r0 = W + (size_t)t * K, *r1 = W + (size_t)(H + t) * K;
    const int8_t *r2 = W + (size_t)(2 * H + t) * K, *r3 = W + (size_t)(3 * H + t) * K;
    for (int k = 0; k < K;) {
        size_t vl = __riscv_vsetvl_e8m1((size_t)(K - k));
        vint8m1_t x = __riscv_vle8_v_i8m1(v + k, vl);
        a0 = __riscv_vwadd_wv_i32m4_tu(a0, a0, __riscv_vwmul_vv_i16m2(x, __riscv_vle8_v_i8m1(r0 + k, vl), vl), vl);
        a1 = __riscv_vwadd_wv_i32m4_tu(a1, a1, __riscv_vwmul_vv_i16m2(x, __riscv_vle8_v_i8m1(r1 + k, vl), vl), vl);
        a2 = __riscv_vwadd_wv_i32m4_tu(a2, a2, __riscv_vwmul_vv_i16m2(x, __riscv_vle8_v_i8m1(r2 + k, vl), vl), vl);
        a3 = __riscv_vwadd_wv_i32m4_tu(a3, a3, __riscv_vwmul_vv_i16m2(x, __riscv_vle8_v_i8m1(r3 + k, vl), vl), vl);
        k += (int)vl;
    }
    vint32m1_t z = __riscv_vmv_s_x_i32m1(0, 1);
    out[0] = __riscv_vmv_x_s_i32m1_i32(__riscv_vredsum_vs_i32m4_i32m1(a0, z, vlmax));
    out[1] = __riscv_vmv_x_s_i32m1_i32(__riscv_vredsum_vs_i32m4_i32m1(a1, z, vlmax));
    out[2] = __riscv_vmv_x_s_i32m1_i32(__riscv_vredsum_vs_i32m4_i32m1(a2, z, vlmax));
    out[3] = __riscv_vmv_x_s_i32m1_i32(__riscv_vredsum_vs_i32m4_i32m1(a3, z, vlmax));
}

void kernel_lstm_q_s8(const int8_t *input, const int8_t *w_ih, const int8_t *w_hh,
                      const int32_t *b_ih, const int32_t *b_hh,
                      int8_t *h_state, int8_t *c_state, int8_t *output,
                      int input_size, int hidden_size, int Mx, int Mh, int S,
                      int has_bias) {
    const int H = hidden_size;
    if (H > MB_LSTM_Q_MAX_HIDDEN) return;
    for (int t = 0; t < H; t++) {
        int32_t ax[4], ah[4];
        mb_lstm_q_dot4(input, w_ih, input_size, H, t, ax);
        mb_lstm_q_dot4(h_state, w_hh, H, H, t, ah);
        if (has_bias)
            for (int q = 0; q < 4; q++) ax[q] += b_ih[q * H + t] + b_hh[q * H + t];
        mb_lstm_q_cell(ax[0], ax[1], ax[2], ax[3], ah[0], ah[1], ah[2], ah[3], Mx, Mh, S,
                       c_state, mb_lstm_q_hn, t);
    }
    for (int t = 0; t < H; t++) { h_state[t] = mb_lstm_q_hn[t]; output[t] = mb_lstm_q_hn[t]; }
}
"""

FILES = {
    "gemmini_q31_rvv/gemmini_q31_rvv_lstm_q_s8_gemmini_full_c.c": ("gemmini_full_c", "Both matvecs on Gemmini (tiled_matmul_auto, full_C: raw int32), cell on the CPU.", GEMMINI),
    "gemmini_q31/gemmini_q31_lstm_q_s8_gemmini_full_c.c": ("gemmini_full_c", "Both matvecs on Gemmini (tiled_matmul_auto, full_C: raw int32), cell on the CPU.", GEMMINI),
    "rvv/rvv_lstm_q_s8_rvv_dot.c": ("rvv_dot", "RVV int8 dot products, four gate rows per pass, cell scalar.", RVV),
}


def render(algo, what, body):
    return HDR.format(algo=algo, what=what) + lstm_q.c_tables() + lstm_q.C_POST + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    kdir = os.path.join(REPO, "kernels")
    bad = 0
    for rel, (algo, what, body) in FILES.items():
        path = os.path.join(kdir, rel)
        text = render(algo, what, body)
        if a.check:
            ok = os.path.exists(path) and open(path).read() == text
            print(("OK      " if ok else "DIFFERS ") + rel)
            bad += not ok
        else:
            open(path, "w").write(text)
            print("wrote", rel)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
