extern "C" int mb_vk_has_int_dot(void) { return mb_vk_init() ? 0 : R.int_dot; }
const mb_packed *mb_vk_find_packed(const void *w) {
    if (R.packed.empty()) return nullptr;
    auto it = R.packed.find(w);
    return it == R.packed.end() ? nullptr : &it->second;
}

extern "C" void mb_vk_release(size_t mark) {
    // the GPU may still read these: drain first
    if (R.recording) mb_vk_sync();
    while (R.allocs.size() > mark) {
        Alloc a = R.allocs.back();
        // packed-weight registrations naming a freed buffer go with it
        const uint8_t *lo = R.chunks[a.chunk].host + a.prev_used, *hi = lo + a.bytes;
        for (auto it = R.packed.begin(); it != R.packed.end();) {
            const uint8_t *k = (const uint8_t *)it->first, *v = (const uint8_t *)it->second.p;
            if ((k >= lo && k < hi) || (v >= lo && v < hi)) it = R.packed.erase(it);
            else ++it;
        }
        R.allocs.pop_back();
        R.chunks[a.chunk].used = a.prev_used;
        R.in_use -= a.bytes;
    }
    R.cur_chunk = R.allocs.empty() ? (R.chunks.empty() ? -1 : 0) : R.allocs.back().chunk;
    if (R.allocs.empty()) for (auto &c : R.chunks) c.used = 0;
}

extern "C" uint64_t mb_vk_devaddr(const void *p) {
    if (!p) return 0;
    const uint8_t *q = (const uint8_t *)p;
    for (const Chunk &c : R.chunks)
        if (q >= c.host && q < c.host + c.size) return c.dev + (uint64_t)(q - c.host);
    for (const Chunk &c : R.scratch)
        if (c.host && q >= c.host && q < c.host + c.size) return c.dev + (uint64_t)(q - c.host);
    set_error(-7, "pointer %p is not inside an mb_vk_alloc buffer", p);
    return 0;
}

// ------------------------------------------------------------------ commands
static void barrier(VkPipelineStageFlags dst_stage, VkAccessFlags dst_access);
static void begin_cb() {
    if (R.recording) return;
    VkCommandBufferBeginInfo bi = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    if (R.capturing) {
        // a graph keeps its own command buffers, replayed by mb_vk_replay
        VkCommandBufferAllocateInfo cbai = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
        cbai.commandPool = R.pool;
        cbai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
        cbai.commandBufferCount = 1;
        VkCommandBuffer cb;
        VKCHK(vkAllocateCommandBuffers(R.dev, &cbai, &cb));
        R.graphs.back().push_back(cb);
        R.cb_cur = cb;
    } else {
        bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
        R.cb_cur = R.cb;
    }
    VKCHK(vkBeginCommandBuffer(R.cb_cur, &bi));
    if (!R.capturing) vkCmdResetQueryPool(R.cb_cur, R.qpool, 0, R.qcap);
    R.qused = 0;
    R.ts_pending_base = (long)R.ts_ns.size();
    R.recording = 1;
    R.n_in_cb = 0;
    R.last_pipe = VK_NULL_HANDLE;
    // order against everything submitted before (an earlier command buffer of
    // the same graph, or host writes): pipeline barriers reach back across
    // command buffers in submission order
    barrier(VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT);
}

static void barrier(VkPipelineStageFlags dst_stage, VkAccessFlags dst_access) {
    VkMemoryBarrier mb = {VK_STRUCTURE_TYPE_MEMORY_BARRIER};
    mb.srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT | VK_ACCESS_HOST_WRITE_BIT;
    mb.dstAccessMask = dst_access;
    vkCmdPipelineBarrier(R.cb_cur, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT | VK_PIPELINE_STAGE_HOST_BIT, dst_stage, 0,
                         1, &mb, 0, nullptr, 0, nullptr);
}

static void submit_wait(const VkCommandBuffer *cbs, uint32_t n) {
    VkSubmitInfo si = {VK_STRUCTURE_TYPE_SUBMIT_INFO};
    si.commandBufferCount = n;
    si.pCommandBuffers = cbs;
    VKCHK(vkQueueSubmit(R.queue, 1, &si, R.fence));
    // generous timeout; a hung GPU reports instead of blocking forever
    long tmo_s = getenv("MB_VK_TIMEOUT_S") ? atol(getenv("MB_VK_TIMEOUT_S")) : 120;
    VkResult w = vkWaitForFences(R.dev, 1, &R.fence, VK_TRUE, (uint64_t)tmo_s * 1000000000ull);
    if (w != VK_SUCCESS) { set_error((int)w, "vkWaitForFences: VkResult %d (GPU hang or timeout)", (int)w); return; }
    VKCHK(vkResetFences(R.dev, 1, &R.fence));
}

extern "C" void mb_vk_sync(void) {
    if (!R.recording) return;
    R.recording = 0;
    barrier(VK_PIPELINE_STAGE_HOST_BIT, VK_ACCESS_HOST_READ_BIT);
    VKCHK(vkEndCommandBuffer(R.cb_cur));
    if (R.capturing) return;            // a graph's command buffer: kept for mb_vk_replay
    submit_wait(&R.cb, 1);
    if (R.err) return;
    VKCHK(vkResetCommandBuffer(R.cb, 0));
    if (R.qused) {
        std::vector<uint64_t> v(R.qused);
        VKCHK(vkGetQueryPoolResults(R.dev, R.qpool, 0, R.qused, v.size() * 8, v.data(), 8,
                                    VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT));
        for (uint32_t i = 0; i < R.qused; i++) R.ts_ns[R.ts_pending_base + i] = (double)v[i] * R.ts_period;
        R.qused = 0;
    }
}

// ---- replayable graphs (the CUDA-graph analogue): launches between
// capture_begin and capture_end are recorded, not run; replay(g) submits them
// again. Push constants hold GPU addresses, so a replay reads whatever the host
// last wrote into the same buffers. Scratch must not grow while capturing (run
// the same launches once before capturing).
extern "C" int mb_vk_capture_begin(void) {
    if (mb_vk_init()) return -1;
    mb_vk_sync();
    R.capturing = 1;
    R.graphs.emplace_back();
    return (int)R.graphs.size() - 1;
}
extern "C" int mb_vk_capture_end(void) {
    if (!R.capturing) return -1;
    mb_vk_sync();
    R.capturing = 0;
    return (int)R.graphs.size() - 1;
}
extern "C" void mb_vk_replay(int g) {
    if (R.err || g < 0 || g >= (int)R.graphs.size()) { if (!R.err) set_error(-10, "no graph %d", g); return; }
    mb_vk_sync();
    auto &cbs = R.graphs[g];
    if (!cbs.empty()) submit_wait(cbs.data(), (uint32_t)cbs.size());
}
extern "C" int mb_vk_graph_cbs(int g) { return (g >= 0 && g < (int)R.graphs.size()) ? (int)R.graphs[g].size() : -1; }

extern "C" void mb_vk_timestamps(int on) { R.ts_on = on; }
extern "C" void mb_vk_ts_reset(void) {
    if (R.recording) mb_vk_sync();
    R.ts_ns.clear();
}
extern "C" int mb_vk_ts_count(void) { return (int)R.ts_ns.size(); }
extern "C" double mb_vk_ts_ns(int i) { return (i >= 0 && i < (int)R.ts_ns.size()) ? R.ts_ns[i] : -1.0; }
extern "C" int mb_vk_ts(void) {
    if (!R.ts_on || R.capturing || mb_vk_init()) return -1;
    if (R.recording && R.qused + 2 > R.qcap) mb_vk_sync();
    begin_cb();
    vkCmdWriteTimestamp(R.cb_cur, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, R.qpool, R.qused++);
    R.ts_ns.push_back(-1.0);
    return (int)R.ts_ns.size() - 1;
}

// ------------------------------------------------------------------ pipelines
int mb_vk_pipeline(const char *name) { return mb_vk_pipeline_spec(name, nullptr, 0); }

int mb_vk_pipeline_spec(const char *name, const int *consts, int nconsts) {
    if (mb_vk_init()) return -1;
    std::string key = name;
    for (int i = 0; i < nconsts; i++) key += "/" + std::to_string(consts[i]);
    auto it = R.pipe_index.find(key);
    if (it != R.pipe_index.end()) return it->second;
    std::vector<VkSpecializationMapEntry> sme(nconsts > 0 ? nconsts : 0);
    for (int i = 0; i < nconsts; i++) sme[i] = {(uint32_t)i, (uint32_t)(4 * i), 4};
    VkSpecializationInfo si = {(uint32_t)(nconsts > 0 ? nconsts : 0), sme.data(), (size_t)4 * (nconsts > 0 ? nconsts : 0), consts};
    const mb_spirv_entry *e = nullptr;
    for (int i = 0; mb_spirv_table[i].name; i++)
        if (!strcmp(mb_spirv_table[i].name, name)) { e = &mb_spirv_table[i]; break; }
    if (!e) { set_error(-8, "no embedded SPIR-V for '%s'", name); return -1; }
    VkShaderModuleCreateInfo smci = {VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
    smci.codeSize = e->nwords * 4;
    smci.pCode = e->words;
    VkShaderModule sm;
    VKCHK_RET(vkCreateShaderModule(R.dev, &smci, nullptr, &sm), -1);
    VkComputePipelineCreateInfo cpci = {VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO};
    cpci.stage.sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    cpci.stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
    cpci.stage.module = sm;
    cpci.stage.pName = "main";
    if (nconsts > 0) cpci.stage.pSpecializationInfo = &si;
    cpci.layout = R.layout;
    VkPipeline p;
    VkResult r = vkCreateComputePipelines(R.dev, VK_NULL_HANDLE, 1, &cpci, nullptr, &p);
    vkDestroyShaderModule(R.dev, sm, nullptr);
    if (r != VK_SUCCESS) { set_error((int)r, "vkCreateComputePipelines(%s): VkResult %d", name, (int)r); return -1; }
    R.pipes.push_back(p);
    int idx = (int)R.pipes.size() - 1;
    R.pipe_index[key] = idx;
    return idx;
}

mb_pc &mb_pc::p(const void *ptr) {
    n = (n + 7) & ~7u;
    uint64_t a = mb_vk_devaddr(ptr);
    memcpy(b + n, &a, 8);
    n += 8;
    return *this;
}
mb_pc &mb_pc::i(int v) { memcpy(b + n, &v, 4); n += 4; return *this; }
mb_pc &mb_pc::u(uint32_t v) { memcpy(b + n, &v, 4); n += 4; return *this; }
mb_pc &mb_pc::f(float v) { memcpy(b + n, &v, 4); n += 4; return *this; }

void mb_vk_dispatch(int pipe, uint32_t gx, uint32_t gy, uint32_t gz, const mb_pc &pc) {
    if (R.err || pipe < 0) return;
    if (pc.n > R.pc_size) { set_error(-9, "push constants %u > device limit %u", pc.n, R.pc_size); return; }
    if (gx == 0 || gy == 0 || gz == 0) return;
    if (R.recording && R.n_in_cb >= R.flush_every) mb_vk_sync();
    begin_cb();
    if (R.n_in_cb > 0)
        barrier(VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT);
    VkPipeline p = R.pipes[pipe];
    if (p != R.last_pipe) {
        vkCmdBindPipeline(R.cb_cur, VK_PIPELINE_BIND_POINT_COMPUTE, p);
        R.last_pipe = p;
    }
    vkCmdPushConstants(R.cb_cur, R.layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, (pc.n + 3) & ~3u, pc.b);
    vkCmdDispatch(R.cb_cur, gx, gy, gz);
    R.n_in_cb++;
    R.n_total++;
}

void mb_vk_launch1d(int pipe, long n, const mb_pc &pc) {
    if (n <= 0) return;
    long groups = (n + 255) / 256;
    uint32_t mx = R.max_gx < 65535 ? R.max_gx : 65535;
    uint32_t gx = groups < (long)mx ? (uint32_t)groups : mx;
    uint32_t gy = (uint32_t)((groups + gx - 1) / gx);
    mb_vk_dispatch(pipe, gx, gy, 1, pc);
}
