"""Build libmb_vk.so: the ModelBlaster Vulkan backend (runtime + fp32 kernels).

    python build.py [--out DIR] [--cxx g++] [--glslc glslc] [--spirv-only] [--from-spirv DIR]

Two steps, which may run on different machines:

1. shaders/*.comp -> SPIR-V (glslc, from shaderc / the Vulkan SDK) -> one C
   header, mb_vk_spirv.h, with every module as a uint32 array. SPIR-V is
   portable across drivers, so this can run anywhere glslc exists.
2. mb_vk_runtime.cpp + mb_vk_kernels.cpp + that header -> libmb_vk.so (g++,
   Vulkan headers only: libvulkan is dlopen'ed at run time). libstdc++ and
   libgcc are linked statically, so a library built on one Linux runs on
   another with the same or newer glibc (the Steam Deck's SteamOS has no
   compiler; build on a host or in a container under $HOME).

--spirv-only stops after step 1 (writes DIR/mb_vk_spirv.h and the .spv files);
--from-spirv DIR takes a header made that way and does step 2 only.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHADERS = HERE / "shaders"


def compile_spirv(out: Path, glslc: str) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    entries = []
    for comp in sorted(SHADERS.glob("*.comp")):
        spv = out / (comp.stem + ".spv")
        subprocess.run([glslc, "--target-env=vulkan1.2", "-O", f"-I{SHADERS}", str(comp), "-o", str(spv)],
                       check=True)
        words = spv.read_bytes()
        assert len(words) % 4 == 0
        entries.append((comp.stem, words))
    hdr = out / "mb_vk_spirv.h"
    lines = ["// generated by gpu_eval/harness/vulkan/build.py from shaders/*.comp -- do not edit",
             "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
             "struct mb_spirv_entry { const char *name; const uint32_t *words; size_t nwords; };"]
    for name, b in entries:
        ws = [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]
        body = ",".join(f"0x{w:08x}u" for w in ws)
        lines.append(f"static const uint32_t mb_spv_{name}[{len(ws)}] = {{{body}}};")
    lines.append("static const mb_spirv_entry mb_spirv_table[] = {")
    lines += [f'    {{"{n}", mb_spv_{n}, {len(b) // 4}}},' for n, b in entries]
    lines.append("    {NULL, NULL, 0}};")
    hdr.write_text("\n".join(lines) + "\n")
    return hdr


def build_lib(out: Path, spirv_dir: Path, cxx: str) -> Path:
    lib = out / "libmb_vk.so"
    cmd = [cxx, "-std=c++17", "-O2", "-fPIC", "-shared", "-Wall", "-Wno-unused-function",
           f"-I{HERE}", f"-I{spirv_dir}",
           str(HERE / "mb_vk_runtime.cpp"), str(HERE / "mb_vk_kernels.cpp"),
           "-o", str(lib), "-ldl", "-static-libstdc++", "-static-libgcc"]
    inc = os.environ.get("VULKAN_INCLUDE")
    if inc:
        cmd.insert(1, f"-I{inc}")
    subprocess.run(cmd, check=True)
    return lib


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "build"))
    ap.add_argument("--cxx", default=os.environ.get("CXX", "g++"))
    ap.add_argument("--glslc", default=os.environ.get("GLSLC", "glslc"))
    ap.add_argument("--spirv-only", action="store_true")
    ap.add_argument("--from-spirv", default=None)
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if a.from_spirv:
        spirv_dir = Path(a.from_spirv)
    else:
        if not shutil.which(a.glslc):
            print(f"build.py: {a.glslc} not found (install shaderc / glslang, or pass --from-spirv)", file=sys.stderr)
            return 2
        spirv_dir = compile_spirv(out, a.glslc).parent
        if a.spirv_only:
            print(spirv_dir / "mb_vk_spirv.h")
            return 0
    print(build_lib(out, spirv_dir, a.cxx))
    return 0


if __name__ == "__main__":
    sys.exit(main())
