def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--schedule", required=True, help="schedules/scheduled_*.json")
    ap.add_argument("--out-dir",  required=True,
                    help="emits dispatch_table.h + runtime_main.cpp here")
    ap.add_argument("--backend-map", required=True,
                    help="comma-sep <slot>=<label>:<lib.so> (e.g. "
                         "CPU_P=HTA_split:libQnnHta.so,CPU_E=CPU:libQnnCpu.so)")
