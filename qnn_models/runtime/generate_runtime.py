    # Apply partition-coalesce overrides — replace per-op routing with
    # the curated compose-feasibility partition for any network that
    # has one. See PARTITIONING_GUIDE.md §6 for why this is the right
    # granularity for the QNN runtime.
    for entry in args.coalesce_from_partition:
        head, _, tail = entry.partition("=")
        net = head.strip()
        if not net or not tail:
            raise SystemExit(f"--coalesce-from-partition: bad entry '{entry}'")
        path, _, base = tail.partition(":")
        path = path.strip()
        base_seg_id = int(base) if base else 100
        n_before = sum(1 for s in segs if s.network == net)
        segs = coalesce_from_partition(segs, net, path, base_seg_id)
        n_after = sum(1 for s in segs if s.network == net)
        print(f"coalesce-from-partition: {net}: {n_before} → {n_after} entries "
              f"(base_seg_id={base_seg_id}, partition={os.path.basename(path)})")

    for entry in args.coalesce_whole_network:
        head, _, base = entry.partition(":")
        net = head.strip()
        if not net:
            raise SystemExit(f"--coalesce-whole-network: bad entry '{entry}'")
        base_seg_id = int(base) if base else 200
