"""Generate a single-binary QNN runtime from an XPU-RT schedule.

Mirrors the zephyr-chipyard-sw `ingest_xpurt_schedule` + `generate_xpurt_main`
pattern but emits Linux/QNN host code instead of Zephyr/RVV. The output is a
self-contained C++ source + dispatch table that:

    1. dlopen()s every QNN backend the schedule references
       (e.g. libQnnHta.so, libQnnCpu.so).
    2. contextCreateFromBinary()s one pre-built context binary per
       (network, backend) pair the schedule routes work to.
    3. Spawns one std::thread per machine kind in the schedule
       (e.g. CPU_P, CPU_E). Each thread iterates the dispatch table in
       start_time order and takes entries whose hardware_target maps to
       its kind.
    4. Synchronises via per-entry std::counting_semaphore. A worker waits
       on the semaphores of its dependencies (intra-job + cross-job
       time_dependency edges) before invoking; posts its own when done.
    5. The 'invocation' for each entry is QnnGraph_execute on the loaded
       context for (entry.network, entry.kind). See §4 of the README for
       the per-op-routing caveat — today the runtime collapses contiguous
       same-(network, instance, backend) runs into one whole-network
       dispatch on the assigned backend; sub-DLCs would let us drive the
       per-op partition the scheduler actually decided.

CLI:
    python3 generate_runtime.py \\
        --schedule schedules/scheduled_<...>.json \\
        --out-dir qnn_models/runtime/gen/<name> \\
        --backend-map CPU_P=HTA_split:libQnnHta.so,CPU_E=CPU:libQnnCpu.so

The --backend-map is a comma-separated list of `slot=label:libname.so`
triples. The slot matches the schedule's machine slot (CPU_P / CPU_E /
CPU_X), the label matches the profile_hw value (HTA_split, CPU, etc.) so
context binaries can be located, and libname.so names the backend
shared library to dlopen.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field


HEADER = "/* @generated by qnn_models/runtime/generate_runtime.py — do not edit. */"

_INSTANCE_RE = re.compile(r"^(?P<base>.+?)(?P<idx>\d+)$")


def _split_job_name(job: str) -> tuple[str, int]:
    """Split 'dronet0' into ('dronet', 0); names without trailing index → (job, 0)."""
    m = _INSTANCE_RE.match(job)
    if not m:
        return job, 0
    return m.group("base"), int(m.group("idx"))


def _c_ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


@dataclass
class Segment:
    """A contiguous run of same-(network, instance, hw_kind) ops collapsed
    into one runtime dispatch unit. The `seg_id` is the runtime-side
    table position (after re-stamp); `ctx_seg_id` is the on-disk
    context-binary suffix (which slice_to_subonnx.py + slice_from_partition.py
    chose). They differ when --coalesce-from-partition relabels yolov8n's
    27 schedule entries to 2 partition slices: those slices keep the
    slicer's seg_id (e.g. 100, 101) as ctx_seg_id, but get a new
    runtime-side seg_id 0..N-1 so it indexes the completion array
    correctly.

    `actual_backend` is the physical-backend short name (HTA / DSP /
    CPU / GPU) the schedule resolves this entry to after applying
    --per-network-lib overrides. Encoded into the dispatch table at
    emit time so the runtime can spawn one worker per
    (kind, actual_backend) pair — without that, two segments on the
    same scheduler kind (e.g. yolov8n+dronet both on CPU_P/HTA_split)
    serialise through one worker thread even though the underlying
    silicon (HTA + DSP) could run them concurrently.

    The scheduler hands us per-op routing; the QNN runtime can only invoke
    whole sub-graphs (one graphExecute per pre-compiled DLC). We coalesce
    same-backend runs within an instance so each segment maps cleanly onto
    a single graphExecute on a single backend's pre-loaded context.

    The op_ids list is the slice of dispatch_ids the segment covers — for
    today's full-network mode it's informational only (we run the whole
    DLC); when sub-DLC generation lands it becomes the partition spec
    (those ops get their own context binary).
    """
    seg_id:        int
    network:       str
    instance:      int
    kind:          str          # CPU_P | CPU_E | CPU_X
    backend_label: str          # HTA_split | CPU | GPU_fp16
    backend_lib:   str          # libQnnHta.so | libQnnCpu.so
    op_ids:        list[int]    # dispatch_ids in this segment
    start_time_ms: float
    duration_ms:   float
    # entry-id-space dependencies — populated after segments are sorted.
    deps:          list[int] = field(default_factory=list)
    # The seg_id slice_*.py used for the context binary on disk. Equal
    # to seg_id by default; differs when partition-coalesce assigns the
    # runtime a contiguous seg_id but the .bin filename has the slicer's
    # original (e.g. 100, 101).
    ctx_seg_id:     int = -1     # populated to seg_id at construction
    actual_backend: str = ""    # populated at emit time from per_net_lib + slot_to_be


def _resolve_backend_map(spec: str) -> dict[str, tuple[str, str]]:
    """Parse 'CPU_P=HTA_split:libQnnHta.so,CPU_E=CPU:libQnnCpu.so' →
    {'CPU_P': ('HTA_split', 'libQnnHta.so'), 'CPU_E': ('CPU', 'libQnnCpu.so')}."""
    out = {}
    for entry in spec.split(","):
        slot, _, rest = entry.strip().partition("=")
        label, _, lib = rest.partition(":")
        if not slot or not label or not lib:
            raise SystemExit(f"--backend-map: bad entry '{entry}'")
        out[slot.strip()] = (label.strip(), lib.strip())
    return out


def _resolve_per_network_overrides(spec: str | None) -> dict[tuple[str, str], str]:
    """Parse 'yolov8n:HTA_split=libQnnDsp.so,dronet:HTA_split=libQnnHta.so'.

    Returns {(network, backend_label): override_lib}. Used to re-target the
    backend lib on a per-(network, label) basis — e.g. on QRB5165 the
    HTA_split *label* dispatches to libQnnHta.so for dronet (HTA accepts
    its op set) but to libQnnDsp.so for yolov8n (HTA rejects it; DSP
    handles the head's Resize/Slice/Softmax). See
    boards/qrb5165_v66/graphs/yolov8n_HTA_split.json for the partition
    rationale.
    """
    out: dict[tuple[str, str], str] = {}
    if not spec:
        return out
    for entry in spec.split(","):
        head, _, lib = entry.strip().partition("=")
        net, _, label = head.partition(":")
        if not net or not label or not lib:
            raise SystemExit(f"--per-network-lib: bad entry '{entry}'")
        out[(net.strip(), label.strip())] = lib.strip()
    return out


def _machine_slot_to_kind(target: str) -> str:
    """'CPU_P#0' → 'CPU_P'."""
    return target.split("#")[0]


def coalesce_whole_network(
    segs: list[Segment],
    network: str,
    base_seg_id: int = 200,
) -> list[Segment]:
    """Collapse all of `network`'s schedule entries per-instance into a
    single segment. Synthetic equivalent of `coalesce_from_partition`
    against a 1-segment partition file. The runtime expects exactly
    one .bin per instance: `ctx_<network>_<label>_seg<base_seg_id>.bin`
    (the full-network DLC). Useful for the coarse-vs-fine experiment."""
    # Build a virtual partition object with one op per dispatch the
    # network has — only the segment count (== contiguous hw_target
    # groups) matters; with all ops on one target there's exactly 1.
    virtual = {
        "ops": [{"hardware_target": "ANY",
                 "_orig_name": f"{network}_op{i}", "name": f"{network}_op{i}"}
                for i in range(1)]
    }
    # Stash the virtual partition in a temp file path the existing
    # coalesce_from_partition handler reads via json.load — but easier
    # to just inline-call the body. Reuse coalesce_from_partition by
    # writing a 1-segment annotation to a temp file.
    import tempfile
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(virtual, f)
        tmp = f.name
    try:
        return coalesce_from_partition(segs, network, tmp, base_seg_id)
    finally:
        os.unlink(tmp)


def coalesce_from_partition(
    segs: list[Segment],
    network: str,
    partition_path: str,
    base_seg_id: int = 100,
) -> list[Segment]:
    """Collapse all of `network`'s per-op schedule entries into the
    coarser partition the curated annotation file describes.

    The schedule's per-op routing for yolov8n is over-fragmented (18
    segments per instance) because the scheduler treats every QNN op
    independently — but the actual compose-feasibility partition for
    yolov8n on QRB5165 has just 2 segments per instance (103-op HTA
    backbone + 146-op DSP head, see PARTITIONING_GUIDE.md §6 + the
    per-op annotation in qnn_models/boards/qrb5165_v66/graphs/
    yolov8n_HTA_split.json). The runtime can only dispatch full sub-DLCs
    via QnnGraph_execute, so we replace the schedule's per-op entries
    with N partition entries per instance — N = number of contiguous
    hw_target groups in the partition file.

    The new entries' seg_id values match the ones slice_from_partition.py
    used (`base_seg_id`, `base_seg_id + 1`, ...) so the runtime's
    `ctx_<network>_<label>_seg<id>.bin` lookup picks up the contexts
    that build_subdlcs.sh produced.

    Cross-network deps (e.g., a dronet entry depending on yolov8n's
    completion via a `time_dependency` edge) get rewired so they now
    depend on the LAST partition entry (the head) for that instance.
    Inbound deps from outside the coalesced set become deps of the
    FIRST partition entry (the backbone). Intra-network deps disappear
    along with the per-op entries themselves.
    """
    with open(partition_path) as f:
        partition = json.load(f)

    # Group consecutive ops by hardware_target to count partitions.
    n_parts = 0
    last_t = None
    for op in partition.get("ops", []):
        t = op.get("hardware_target")
        if t != last_t:
            n_parts += 1
            last_t = t
    if n_parts == 0:
        raise SystemExit(f"--coalesce-from-partition: {partition_path} "
                         f"has no ops with hardware_target")

    # Pull the existing entries we're about to replace, plus everyone else.
    drop:    list[Segment] = []
    keep:    list[Segment] = []
    for s in segs:
        if s.network == network:
            drop.append(s)
        else:
            keep.append(s)
    if not drop:
        return segs   # nothing to coalesce

    # Group dropped entries by instance.
    by_inst: dict[int, list[Segment]] = defaultdict(list)
    for s in drop:
        by_inst[s.instance].append(s)

    # Build a redirect: any old seg_id → its instance's last partition
    # seg_id. Other segments that had a dep into the coalesced set get
    # rewritten to point at the head of the partition for that instance.
    redirect: dict[int, int] = {}
    new_partition_segs: list[Segment] = []
    # Use the same backend_label/kind/lib taxonomy as the schedule's
    # own entries — all the dropped entries share the network's label
    # universe (e.g. yolov8n in our case routes only to HTA_split + CPU,
    # both of which collapse to a single per-network backend at the
    # partition level since the partition is single-network/single-label
    # by construction).
    label = drop[0].backend_label
    kind  = drop[0].kind
    be_lib = drop[0].backend_lib

    # Allocate a contiguous seg_id range PER INSTANCE so multi-instance
    # networks (e.g. 5 dronet instances) don't all collide at base_seg_id.
    # Within an instance, the partition's N segments still occupy
    # consecutive seg_ids starting at this offset; the .bin lookup uses
    # ctx_seg_id (which we set to the per-instance seg_id) so the
    # runtime's per-segment context cache aliases instances of the same
    # shape to one loaded ctx (see g_ctx alias_to_ctx_key in the
    # template).
    inst_offsets: dict[int, int] = {}
    cursor = base_seg_id
    for inst in sorted(by_inst.keys()):
        inst_offsets[inst] = cursor
        cursor += n_parts

    for inst, lst in by_inst.items():
        lst.sort(key=lambda s: s.start_time_ms)
        # Inbound deps come from upstream segments outside the dropped set.
        all_old_ids = {s.seg_id for s in lst}
        upstream: set[int] = set()
        for s in lst:
            for d in s.deps:
                if d not in all_old_ids:
                    upstream.add(d)
        # Time bounds — collapse durations into the partitions.
        first_t = lst[0].start_time_ms
        total_d = sum(s.duration_ms for s in lst)
        per_d = total_d / n_parts

        per_inst_seg_ids: list[int] = []
        for p in range(n_parts):
            sid = inst_offsets[inst] + p
            per_inst_seg_ids.append(sid)
            # Explicit ctx_seg_id: each instance's partition-N segment
            # points at the SAME .bin (base_seg_id + p), regardless of
            # which instance — so 5 dronet instances all reuse one
            # ctx_dronet_HTA_split_seg200.bin rather than each requiring
            # its own copy. The runtime's alias_to_ctx_key map collapses
            # them to a single shared loaded context.
            #
            # Stagger predicted start_time_ms across partitions:
            # partition p starts after partition p-1 finishes (rough
            # equal-share guess based on total dropped duration). Without
            # this every partition would have the same start_time — the
            # Gantt then shows the bars on top of each other and only
            # the last-emitted is visible.
            seg = Segment(
                seg_id=sid,
                ctx_seg_id=base_seg_id + p,
                network=network,
                instance=inst,
                kind=kind,
                backend_label=label,
                backend_lib=be_lib,
                op_ids=[],          # not meaningful for partition slices
                start_time_ms=first_t + p * per_d,
                duration_ms=per_d,
                deps=(sorted(upstream) if p == 0
                       else [per_inst_seg_ids[-2]]),
            )
            new_partition_segs.append(seg)
        # All old yolov8n seg_ids redirect → the head partition for this instance.
        head_id = per_inst_seg_ids[-1]
        for old_id in all_old_ids:
            redirect[old_id] = head_id

    # Rewire any dep in the kept set that pointed at a dropped seg_id.
    for s in keep:
        s.deps = sorted({redirect.get(d, d) for d in s.deps})

    # Final segment list — kept entries + new partition entries.
    out = keep + new_partition_segs
    out.sort(key=lambda s: (s.start_time_ms, s.network, s.instance, s.kind))
    return out


def restamp_seg_ids(segs: list[Segment]) -> list[Segment]:
    """Re-number seg_ids to a contiguous 0..N-1 range while preserving
    the .bin-on-disk seg_id under ctx_seg_id. The runtime indexes its
    completion[] array by table-position seg_id, so any sparse numbering
    (e.g. coalesced partition entries at 100/101 alongside dronet 0..6)
    indexes out of bounds. This pass is the bridge between the slicer's
    seg_id (which names the context binary) and the runtime's seg_id
    (which names the table slot).
    """
    # First pass: build old → new seg_id map. For segments where
    # ctx_seg_id was already set explicitly (partition coalesce shares
    # one .bin across instances), preserve that ctx_seg_id verbatim;
    # only the unset-default (-1) case gets ctx_seg_id = old seg_id.
    remap: dict[int, int] = {}
    for new_id, s in enumerate(segs):
        remap[s.seg_id] = new_id
    for s in segs:
        if s.ctx_seg_id == -1:
            s.ctx_seg_id = s.seg_id
    # Second pass: rewrite seg_id and deps through the remap.
    for s in segs:
        s.seg_id = remap[s.seg_id]
        s.deps = [remap[d] for d in s.deps if d in remap]
    return segs


_SEG_NAME_RE = re.compile(r"^(?P<net>[A-Za-z][A-Za-z0-9]*)_(?P<label>.+)_seg(?P<idx>\d+)$")
# Coarse-grained schedules (one whole-network DLC per dispatch) name their
# module as "<net>_<label>" (no _seg<N>) — e.g. "dronet_full". The runtime
# treats those as ctx_seg_id=0 and the .bin lookup becomes
# ctx_<net>_<label>_seg0__<Be>.bin (we symlink the actual <net>_<label>__<Be>.bin
# at this name on the board).
_COARSE_NAME_RE = re.compile(r"^(?P<net>[A-Za-z][A-Za-z0-9]*)_(?P<label>.+)$")


def segments_from_segmented_schedule(
    sched: dict, slot_to_be: dict[str, tuple[str, str]]
) -> list[Segment]:
    """Variant of coalesce_segments for already-segmented schedules where
    each dispatch IS one sub-DLC (the MILP path on networks_segmented_*).

    Each dispatch becomes a Segment whose:
      - network         = parsed from module_name's leading token
      - backend_label   = parsed from module_name's middle (e.g. HTA_split, CPU)
      - ctx_seg_id      = parsed segment index (0..6 for dronet, 100..101 for yolov8n)
      - actual_backend  = resolved later from kind via slot_to_be (and
                          --per-network-lib overrides) at emit time

    Importantly we DO NOT merge consecutive same-kind dispatches: each one
    has its own pre-built ctx_<net>_<label>_seg<idx>__<Be>.bin on the
    board. Merging would point at a non-existent combined ctx.
    """
    rows = []
    for k, d in sched["dispatches"].items():
        net, inst = _split_job_name(d["job_name"])
        # The segmented toplevel uses identifier="<net>_segmented" so the
        # network names in the schedule are e.g. "dronet_segmented",
        # "yolov8n_segmented". The on-disk ctx files keep the original
        # network name (dronet, yolov8n) — strip the "_segmented" suffix
        # so ctx_key construction matches the .bin layout from
        # profile_sweep.sh.
        for suffix in ("_segmented", "_coarse"):
            if net.endswith(suffix):
                net = net[: -len(suffix)]
                break
        kind = _machine_slot_to_kind(d["hardware_target"])
        if kind not in slot_to_be:
            raise SystemExit(
                f"schedule routes to slot {kind!r} but --backend-map has no entry for it. "
                f"Known: {list(slot_to_be)}")
        # Net comes from job_name (post-_segmented/_coarse strip). Strip
        # the same "<net>_" prefix off module_name so the remainder is
        # the segment label (handles multi-word net names like
        # "mlp_control" — the previous regex split on the first
        # underscore and got net="mlp", label="control_full").
        mod = d.get("module_name", "")
        prefix = net + "_"
        if mod.startswith(prefix):
            tail = mod[len(prefix):]
        else:
            tail = mod
        # tail is now "<label>_seg<idx>" (segmented) or "<label>" (coarse).
        m_seg = re.match(r"^(?P<label>.+)_seg(?P<idx>\d+)$", tail)
        if m_seg:
            seg_label = m_seg.group("label")
            ctx_idx = int(m_seg.group("idx"))
        elif tail:
            seg_label = tail
            ctx_idx = 0
        else:
            raise SystemExit(
                f"--from-segmented-schedule: dispatch {k} module_name "
                f"{mod!r} doesn't carry a recognizable label after "
                f"stripping net prefix '{prefix}'.")
        rows.append((d["job_name"], net, inst, d["start_time"],
                     d["id"], kind, seg_label, ctx_idx, d))
    # Sort by start time so seg_id ordering reflects schedule progression.
    rows.sort(key=lambda r: (r[3], r[0], r[4]))

    segs: list[Segment] = []
    for job, net, inst, st, did, kind, seg_label, ctx_idx, d in rows:
        # backend_label here is the *segment label* (HTA_split / CPU), not
        # the slot's default label. The actual_backend is filled in by
        # the emit step from slot_to_be + per_net_lib so it can differ
        # from the segment label (e.g. dronet_HTA_split_seg0 may run on
        # Dsp/Hta/Cpu — MILP picks per-segment).
        _, slot_lib = slot_to_be[kind]
        s = Segment(
            seg_id=-1, network=net, instance=inst, kind=kind,
            backend_label=seg_label, backend_lib=slot_lib,
            op_ids=[did], start_time_ms=float(st),
            duration_ms=float(d["duration"]),
            ctx_seg_id=ctx_idx,
        )
        segs.append(s)

    # Assign monotonic seg_id by start_time order so the runtime walker
    # makes forward progress.
    segs.sort(key=lambda s: (s.start_time_ms, s.network, s.instance, s.ctx_seg_id))
    for i, s in enumerate(segs):
        s.seg_id = i

    # Within each (net, inst), segment N depends on segment N-1 in
    # start_time order — same as coalesce_segments.
    by_inst: dict[tuple[str, int], list[Segment]] = defaultdict(list)
    for s in segs:
        by_inst[(s.network, s.instance)].append(s)
    for (net, inst), lst in by_inst.items():
        lst.sort(key=lambda s: s.start_time_ms)
        for i in range(1, len(lst)):
            lst[i].deps.append(lst[i - 1].seg_id)
    return segs


def coalesce_segments(sched: dict, slot_to_be: dict[str, tuple[str, str]]) -> list[Segment]:
    """Walk the schedule's dispatches in start_time order and group
    contiguous same-(network, instance, kind) runs into segments.

    Within one (network, instance) the scheduler can hop kinds; each hop
    starts a new segment. The segment's start_time is its first op's
    start_time, duration is sum of the contained ops.

    Entry IDs (segment-table position) and deps are filled in by the
    caller after the global sort.
    """
    # Sort dispatches by (job, start_time, dispatch_id). job-grouping first
    # so two instances of the same network don't braid in confusing ways.
    rows = []
    for k, d in sched["dispatches"].items():
        net, inst = _split_job_name(d["job_name"])
        kind = _machine_slot_to_kind(d["hardware_target"])
        if kind not in slot_to_be:
            raise SystemExit(
                f"schedule routes to slot {kind!r} but --backend-map has no entry for it. "
                f"Known: {list(slot_to_be)}")
        rows.append((d["job_name"], net, inst, d["start_time"], d["id"], kind, k, d))

    rows.sort(key=lambda r: (r[0], r[3], r[4]))

    segs: list[Segment] = []
    cur: Segment | None = None
    for job, net, inst, st, did, kind, key, d in rows:
        be_label, be_lib = slot_to_be[kind]
        if (cur is None or
            cur.network != net or cur.instance != inst or cur.kind != kind):
            if cur is not None:
                segs.append(cur)
            cur = Segment(
                seg_id=-1, network=net, instance=inst, kind=kind,
                backend_label=be_label, backend_lib=be_lib,
                op_ids=[did], start_time_ms=float(st),
                duration_ms=float(d["duration"]),
            )
        else:
            cur.op_ids.append(did)
            cur.duration_ms += float(d["duration"])
    if cur is not None:
        segs.append(cur)

    # Assign entry ids by start_time-then-job order (so the worker walker
    # makes monotonic progress). Within an instance, same-backend hops keep
    # their original op order via the segment's op_ids list.
    segs.sort(key=lambda s: (s.start_time_ms, s.network, s.instance, s.kind))
    for i, s in enumerate(segs):
        s.seg_id = i

    # Compute deps: a segment depends on the latest segment ending before
    # it from the same (network, instance) — that's the implicit producer
    # of the boundary tensor — plus any segment from the SAME (net, inst)
    # whose last op's dispatch_id is the predecessor of this segment's
    # first op (handles non-linear DAGs where a later-starting segment may
    # depend on an earlier-finishing one in a different kind).
    by_inst: dict[tuple[str, int], list[Segment]] = defaultdict(list)
    for s in segs:
        by_inst[(s.network, s.instance)].append(s)
    # within each (net, inst) the segments in start_time order — every
    # segment depends on the immediately preceding segment in that instance
    # (data deps inside one inference are handled by the original
    # dispatch_id ordering; the schedule respects them).
    for (net, inst), lst in by_inst.items():
        lst.sort(key=lambda s: s.start_time_ms)
        for i in range(1, len(lst)):
            lst[i].deps.append(lst[i - 1].seg_id)

    return segs


def emit_dispatch_table(segs: list[Segment],
                          manifest: dict | None = None,
                          graph_index: dict | None = None,
                          conv_name_resolver: dict | None = None) -> str:
    """Emit a C source array of segment records the worker walker reads."""
    lines = []
    lines.append(HEADER)
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("struct ScheduleEntry {")
    lines.append("    int          seg_id;")
    lines.append("    int          ctx_seg_id;     /* on-disk .bin suffix; differs from seg_id when partition-coalesced */")
    lines.append("    const char*  network;        /* e.g. 'dronet' */")
    lines.append("    int          instance;       /* periodic instance idx, 0 for unique */")
    lines.append("    const char*  kind;           /* CPU_P / CPU_E / CPU_X */")
    lines.append("    const char*  backend_label;  /* HTA_split / CPU — names the loaded ctx */")
    lines.append("    const char*  actual_backend; /* HTA / DSP / CPU / GPU — physical lib resolution */")
    lines.append("    int          n_ops;          /* #dispatch_ids in this segment */")
    lines.append("    const int*   op_ids;         /* into the network's IR dispatch_id space */")
    lines.append("    double       start_time_ms;  /* schedule-side predicted start */")
    lines.append("    double       duration_ms;    /* schedule-side predicted total */")
    lines.append("    int          n_deps;")
    lines.append("    const int*   deps;           /* seg_ids of producers */")
    lines.append("    int          n_input_tensors;")
    lines.append("    const char* const* input_tensor_names;   /* boundary input names — for cross-segment handoff */")
    lines.append("    int          n_output_tensors;")
    lines.append("    const char* const* output_tensor_names;")
    lines.append("    const char*  ctx_bin_name;     /* optional override for the .bin filename (multi-graph ctx). Empty = legacy single-graph path */")
    lines.append("    const char*  graph_name;       /* which graph inside the ctx to retrieve (empty = use the first/only graph for legacy ctx) */")
    lines.append("};")
    lines.append("")

    # Per-segment tensor name arrays — populated from the slicer's manifest.json
    # when `--manifest` is set. Without a manifest, both arrays are empty
    # and the runtime treats input as zero-initialised + drops outputs (i.e.
    # the previous timing-only behaviour).
    seg_io: dict[int, tuple[list[str], list[str]]] = {}
    if manifest:
        # Manifest entries identify segments by ctx_seg_id (the .bin
        # suffix the slicer chose), since restamp_seg_ids may have
        # renumbered the runtime-side seg_id. Match on (network,
        # ctx_seg_id).
        by_ctx_key: dict[tuple[str, int], dict] = {}
        for m in manifest.get("segments", []):
            if "alias_of" in m: continue
            by_ctx_key[(m["network"], m["seg_id"])] = m
        for s in segs:
            key = (s.network, s.ctx_seg_id)
            m = by_ctx_key.get(key)
            if m is None:
                seg_io[s.seg_id] = ([], [])
                continue
            seg_io[s.seg_id] = (list(m.get("input_tensors", [])),
                                 list(m.get("output_tensors", [])))
    def _q(x: str) -> str:
        # C++ string-literal escape — double-quote, escape backslashes
        # and embedded double quotes. Tensor names from ONNX may
        # contain '/' and '.' which are fine in a C string literal.
        return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'

    for s in segs:
        ins, outs = seg_io.get(s.seg_id, ([], []))
        if ins:
            lines.append(f'static const char* const seg{s.seg_id}_in_names[] = '
                         f'{{ {", ".join(_q(x) for x in ins)} }};')
        else:
            lines.append(f'static const char* const seg{s.seg_id}_in_names[] = {{ "" }};')
        if outs:
            lines.append(f'static const char* const seg{s.seg_id}_out_names[] = '
                         f'{{ {", ".join(_q(x) for x in outs)} }};')
        else:
            lines.append(f'static const char* const seg{s.seg_id}_out_names[] = {{ "" }};')

    # Per-segment op_id and deps arrays.
    for s in segs:
        lines.append(f"static const int seg{s.seg_id}_ops[] = {{ "
                      f"{', '.join(str(i) for i in s.op_ids)} }};")
        if s.deps:
            lines.append(f"static const int seg{s.seg_id}_deps[] = {{ "
                          f"{', '.join(str(i) for i in s.deps)} }};")
        else:
            lines.append(f"static const int seg{s.seg_id}_deps[] = {{ 0 }};  /* unused, n_deps=0 */")

    lines.append("")
    # Helper: look up (ctx_bin_name, graph_name) for a segment from the
    # graph_index. The graph_index is keyed by graph_name then by backend
    # (upper-cased: CPU / DSP / HTA). For our v3 bundle case the
    # segment_name in the schedule == graph_name in the ctx binary.
    # If no graph_index given OR no match for this segment, both fields
    # empty (legacy single-graph path).
    def _graph_lookup(seg):
        if not graph_index:
            return ("", "")
        g_name = seg.backend_label
        # If the schedule used a synthetic conv pseudo-name (e.g.
        # 'dsp_seg_01_conv1'), translate to the real conv-node-name from
        # segment_perf.json so it matches the graph name inside the conv DLC.
        if conv_name_resolver and g_name in conv_name_resolver:
            g_name = conv_name_resolver[g_name]
        be = (seg.actual_backend or "").upper()
        bemap = graph_index.get(g_name)
        if not bemap: return ("", "")
        info = bemap.get(be)
        if not info: return ("", "")
        return (info["bin"], g_name)

    lines.append(f"#define SCHEDULE_N_ENTRIES {len(segs)}")
    lines.append("static const ScheduleEntry SCHEDULE_TABLE[SCHEDULE_N_ENTRIES] = {")
    for s in segs:
        ins, outs = seg_io.get(s.seg_id, ([], []))
        ctx_bin, gname = _graph_lookup(s)
        lines.append(
            f"    {{ {s.seg_id}, {s.ctx_seg_id}, \"{s.network}\", {s.instance}, "
            f"\"{s.kind}\", \"{s.backend_label}\", \"{s.actual_backend or '?'}\", "
            f"{len(s.op_ids)}, "
            f"seg{s.seg_id}_ops, {s.start_time_ms:.6f}, {s.duration_ms:.6f}, "
            f"{len(s.deps)}, seg{s.seg_id}_deps, "
            f"{len(ins)}, seg{s.seg_id}_in_names, "
            f"{len(outs)}, seg{s.seg_id}_out_names, "
            f"\"{ctx_bin}\", \"{gname}\" }},"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


